class SpikeError(Exception):
    """A step the spike cannot continue past."""


def wrangler_bin() -> str:
    return os.environ.get("WRANGLER_BIN") or str(DEFAULT_WRANGLER)


def write_scratch(
    version: str, key: str, executor: bool = True, scratch: pathlib.Path = SCRATCH
) -> None:
    """The scratch Worker, rewritten whole; the key and version are the only things that vary."""
    (scratch / "src").mkdir(parents=True, exist_ok=True)
    (scratch / "container").mkdir(parents=True, exist_ok=True)
    (scratch / "wrangler.toml").write_text(
        WRANGLER_TOML.format(
            name=WORKER_NAME, version=version, key=key, executor=EXECUTOR_IMAGE if executor else ""
        ),
        encoding="utf-8",
    )
    (scratch / "src" / "index.mjs").write_text(WORKER_SOURCE, encoding="utf-8")
    (scratch / "container" / "Dockerfile").write_text(DOCKERFILE, encoding="utf-8")
    (scratch / "container" / "server.mjs").write_text(CONTAINER_SERVER, encoding="utf-8")


def wrangler(
    args: list[str], *, cwd: pathlib.Path = SCRATCH, timeout: int = 1500
) -> subprocess.CompletedProcess:
    """One wrangler call; both streams captured so no run output carries an unvetted line to a terminal."""
    return subprocess.run(
        [wrangler_bin(), *args],
        cwd=cwd,
        capture_output=True,
        text=True,
        timeout=timeout,
        check=False,
    )


def tail(text: str, lines: int = 12) -> str:
    return "\n".join((text or "").strip().splitlines()[-lines:])


def deploy_state_path(scratch: pathlib.Path = SCRATCH) -> pathlib.Path:
    return scratch / "deploy.json"


def load_state(scratch: pathlib.Path = SCRATCH) -> dict[str, Any]:
    path = deploy_state_path(scratch)
    if not path.is_file():
        raise SpikeError("no deploy record at %s: run the deploy verb first" % path)
    return json.loads(path.read_text(encoding="utf-8"))


def deploy(
    version: str = "v1",
    executor: bool = True,
    scratch: pathlib.Path = SCRATCH,
    key: str | None = None,
) -> dict[str, Any]:
    """Write the scratch Worker and `wrangler deploy` it; the record keeps the workers.dev URL and the access key."""
    prior = deploy_state_path(scratch)
    prev = json.loads(prior.read_text()) if prior.is_file() else {}
    if key is None:
        key = prev.get("key") or secrets.token_hex(16)
    write_scratch(version, key, executor, scratch)
    started = time.time()
    result = wrangler(["deploy", "--config", "wrangler.toml"], cwd=scratch)
    out = (result.stdout or "") + "\n" + (result.stderr or "")
    if result.returncode != 0:
        raise SpikeError("wrangler deploy exited %d:\n%s" % (result.returncode, tail(out, 25)))
    url = WORKERS_DEV_URL.search(out)
    version_id = re.findall(r"Current Version ID:\s*(\S+)", out)
    state = {
        "worker": WORKER_NAME,
        "url": url.group(0) if url else prev.get("url"),
        "key": key,
        "version": version,
        "version_id": version_id[-1] if version_id else None,
        "executor_image": executor,
        "deploy_s": round(time.time() - started, 1),
    }
    if not state["url"]:
        raise SpikeError("wrangler deploy printed no workers.dev URL:\n%s" % tail(out, 25))
    deploy_state_path(scratch).write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")
    print(
        "deployed %s version=%s version_id=%s url=%s (%.1fs)"
        % (WORKER_NAME, version, state["version_id"], state["url"], state["deploy_s"])
    )
    return state


class Worker:
    """The deployed scratch Worker over HTTP."""

    def __init__(self, url: str, key: str):
        self.url = url.rstrip("/")
        self.key = key

    def call(self, name: str, op: str, timeout: int = 150, **params: Any) -> dict[str, Any]:
        query = "&".join("%s=%s" % (k, v) for k, v in params.items() if v is not None)
        request = https.build_request(
            "%s/do/%s/%s?%s" % (self.url, name, op, query),
            headers={"x-spike-key": self.key, "user-agent": USER_AGENT},
            http="loopback",
        )
        try:
            with https.urlopen(request, timeout=timeout, http="loopback") as resp:
                return json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as exc:
            body = exc.read().decode("utf-8", "replace")
            try:
                return {"http_status": exc.code, **json.loads(body)}
            except ValueError:
                return {"http_status": exc.code, "error": body[:300]}
        except (urllib.error.URLError, TimeoutError, OSError) as exc:
            return {"error": "transport: %s" % exc}

    def ping(self) -> bool:
        try:
            request = https.build_request(
                self.url + "/ping", headers={"user-agent": USER_AGENT}, http="loopback"
            )
            with https.urlopen(request, timeout=30, http="loopback") as resp:
                return resp.read() == b"pong"
        except (urllib.error.URLError, OSError):
            return False


def answers_of(reply: dict[str, Any]) -> list[dict[str, Any]]:
    """The echo answers a `call` reply carries (empty when the call failed)."""
    result = reply.get("result")
    return [a for a in result if isinstance(a, dict)] if isinstance(result, list) else []


def props_of(answer: dict[str, Any]) -> dict[str, Any] | None:
    body = answer.get("body")
    return body.get("props") if isinstance(body, dict) else None


def prove_du1(worker: Worker, orgs: tuple[str, str] = ("org-a", "org-b")) -> dict[str, Any]:
    """DU1: interleaved calls from two instances each get exactly their own props; then rotated props after re-registration."""
    started = {
        o: worker.call(o, "start", org=o, size="custom", image="tiny", reg="before", rot=0)
        for o in orgs
    }
    ids = {o: started[o].get("containerId") for o in orgs}
    cross = 0
    answered = 0
    missing = 0
    retries = 0
    failures: list[str] = []
    for _ in range(CALLS_PER_ORG):
        for o in orgs:
            got = []
            for _attempt in range(TRANSIENT_RETRIES):
                got = answers_of(worker.call(o, "call", org=o, n=1))
                if got and props_of(got[0]):
                    break
                retries += 1
                failures.append(json.dumps(got[:1])[:200] if got else "no answer")
            if not got:
                missing += 1
            for a in got:
                answered += 1
                props = props_of(a)
                if not props:
                    missing += 1
                elif props.get("orgId") != o or props.get("containerId") != ids[o]:
                    cross += 1
    rotated = worker.call(orgs[0], "reregister", org=orgs[0], rot=1)
    after = answers_of(worker.call(orgs[0], "call", org=orgs[0], n=1))
    other = answers_of(worker.call(orgs[1], "call", org=orgs[1], n=1))
    rot_a = (props_of(after[0]) or {}).get("rot") if after else None
    rot_b = (props_of(other[0]) or {}).get("rot") if other else None
    return {
        "started": {
            o: {k: started[o].get(k) for k in ("accepted", "ready", "ready_ms", "error")}
            for o in orgs
        },
        "calls": CALLS_PER_ORG * len(orgs),
        "answered": answered,
        "missing_props": missing,
        "transient_retries": retries,
        "transient_samples": failures[:3],
        "cross_answers": cross,
        "distinct_container_ids": len({v for v in ids.values() if v}),
        "reregister_ok": rotated.get("reregistered") is True,
        "rotated_props_seen": rot_a == 1 and rot_b == 0,
        "rot_a_after": rot_a,
        "rot_b_after": rot_b,
    }


def prove_du2(
    worker: Worker, redeploy, orgs: tuple[str, str] = ("org-a", "org-b")
) -> dict[str, Any]:
    """DU2: a new Worker version deployed while both containers run; does the intercept still answer, and did the Durable Object restart."""
    before = {o: worker.call(o, "inspect", org=o) for o in orgs}
    boots_before = {o: before[o].get("boot") for o in orgs}
    new_version = redeploy()
    restarted = False
    deadline = time.time() + 90
    after: dict[str, Any] = {}
    while time.time() < deadline:
        after = {o: worker.call(o, "inspect", org=o) for o in orgs}
        restarted = all(
            after[o].get("boot") and after[o].get("boot") != boots_before[o] for o in orgs
        )
        if restarted and all(after[o].get("version") == new_version for o in orgs):
            break
        time.sleep(3)

    def probe() -> dict[str, bool]:
        ok = {}
        for o in orgs:
            got = answers_of(worker.call(o, "call", org=o, n=1))
            props = props_of(got[0]) if got else None
            ok[o] = bool(props and props.get("orgId") == o)
        return ok

    without = probe()
    survived = all(without.values())
    fixed_by_reregister = None
    if not survived:
        for o in orgs:
            worker.call(o, "reregister", org=o, rot=2)
        fixed_by_reregister = all(probe().values())
    return {
        "new_version": new_version,
        "durable_object_restarted": restarted,
        "versions_after": {o: after[o].get("version") for o in orgs} if after else None,
        "ctor_saw_running_container": (
            all(after[o].get("ctorRunning") is True for o in orgs) if after else None
        ),
        "intercept_survived_without_reregister": survived,
        "reregister_needed_and_works": fixed_by_reregister,
    }


def median(values: list[float]) -> float | None:
    return round(statistics.median(values), 1) if values else None


def prove_du3(worker: Worker, executor: bool) -> dict[str, Any]:
    """DU3: which sizes `start()` accepts, the cold-start median per accepted size, and the executor image's idle memory under `lite`."""
    sizes: dict[str, Any] = {}
    for size in ("lite", "standard-1", "custom", "basic"):
        tries = []
        accepted = None
        error = None
        for i in range(COLD_STARTS if size != "basic" else 1):
            name = "cold-%s-%d" % (size, i)
            for _attempt in range(TRANSIENT_RETRIES):
                got = worker.call(
                    name, "start", org=name, size=size, image="tiny", reg="before", budget=60000
                )
                transient = "502" in str(got.get("error")) or "transport" in str(got.get("error"))
                if got.get("ready") or not transient:
                    break
                worker.call(name, "stop", org=name)
            accepted = bool(got.get("ready"))
            if not accepted:
                error = got.get("error")
                worker.call(name, "stop", org=name)
                break
            tries.append(got.get("ready_ms") or 0)
            worker.call(name, "stop", org=name)
        sizes[size] = {
            "accepted": accepted,
            "error": error,
            "ready_ms": tries,
            "cold_start_median_ms": median(tries),
        }
    idle: dict[str, Any] = {"measured": False}
    if executor:
        name = "exec-lite"
        got = worker.call(
            name, "start", org=name, size="lite", image="executor", reg="before", budget=120000
        )
        idle = {
            "measured": False,
            "start": {k: got.get(k) for k in ("accepted", "ready", "ready_ms", "error")},
        }
        if got.get("ready"):
            time.sleep(45)
            mem = worker.call(name, "exec-mem", org=name)
            idle["exec_mem"] = {k: mem.get(k) for k in ("stdout", "exitCode", "error")}
            nums = re.findall(r"^\d+$", mem.get("stdout") or "", re.MULTILINE)
            info = dict(
                re.findall(
                    r"^(MemTotal|MemAvailable):\s+(\d+) kB", mem.get("stdout") or "", re.MULTILINE
                )
            )
            if len(info) == 2:
                idle["meminfo_used_mib"] = round(
                    (int(info["MemTotal"]) - int(info["MemAvailable"])) / 1024, 1
                )
                idle["meminfo_total_mib"] = round(int(info["MemTotal"]) / 1024, 1)
                idle["measured"] = True
            if len(nums) >= 2:
                idle.update(
                    {
                        "measured": True,
                        "idle_current_mib": round(int(nums[0]) / 2**20, 1),
                        "idle_peak_mib": round(int(nums[1]) / 2**20, 1),
                    }
                )
        worker.call(name, "stop", org=name)
    return {
        "sizes": sizes,
        "executor_under_lite": idle,
        "machine_status_peak_mib": None,
        "machine_status_note": "not measured: `machine status` needs a customer machine and an issued token, neither exists on a scratch Worker",
    }


def prove_du7(worker: Worker, name: str = "org-a") -> dict[str, Any]:
    """DU7: with `enableInternet: true` the container opens TCP 22 to a public host and reads its SSH banner."""
    got = worker.call(name, "tcp", org=name, host="github.com", port=22)
    result = got.get("result") or {}
    return {
        "host": "github.com",
        "port": 22,
        "result": result,
        "reachable": str(result.get("banner", "")).startswith("SSH-"),
    }


def prove_public_route(worker: Worker, name: str = "org-a") -> dict[str, Any]:
    """The Design C premise: the container reaches the Worker's own public URL."""
    got = worker.call(name, "fetch", org=name, url=worker.url + "/ping")
    result = got.get("result") or {}
    return {
        "result": result,
        "reachable": result.get("status") == 200 and result.get("text") == "pong",
    }


def prove_du6(scratch: pathlib.Path = SCRATCH) -> dict[str, Any]:
    """DU6: wrangler's answer to `max_instances` on a `durable_object` entry (a dry run that builds no container)."""
    planted = scratch / "wrangler.planted.toml"
    planted.write_text(PLANTED_MAX_INSTANCES, encoding="utf-8")
    result = wrangler(
        ["deploy", "--dry-run", "--containers-rollout", "none", "--config", planted.name],
        cwd=scratch,
        timeout=900,
    )
    text = (result.stdout or "") + "\n" + (result.stderr or "")
    if result.returncode == 0:
        outcome = "ignored"
    elif "max_instances" in text:
        outcome = "refused"
    else:
        outcome = "refused-other"
    return {"rc": result.returncode, "outcome": outcome, "message": tail(text, 6)}


def prove_du5(scratch: pathlib.Path = SCRATCH, port: int = 8799) -> dict[str, Any]:
    """DU5: `wrangler dev` runs a `durable_object`-policy container and its intercept locally (tiny image only; Docker builds it)."""
    config = scratch / "wrangler.dev-spike.toml"
    state = load_state(scratch)
    config.write_text(
        WRANGLER_TOML.format(
            name=WORKER_NAME + "-dev", version="dev", key=state["key"], executor=""
        ),
        encoding="utf-8",
    )
    log = scratch / "wrangler-dev.log"
    with open(log, "w", encoding="utf-8") as sink:
        proc = subprocess.Popen(
            [
                wrangler_bin(),
                "dev",
                "--config",
                config.name,
                "--port",
                str(port),
                "--ip",
                "127.0.0.1",
            ],
            cwd=scratch,
            stdout=sink,
            stderr=subprocess.STDOUT,
            start_new_session=True,
        )
    out: dict[str, Any] = {"port": port, "log": log.name}
    try:
        worker = Worker("http://127.0.0.1:%d" % port, state["key"])
        deadline = time.time() + 420
        up = False
        while time.time() < deadline and proc.poll() is None:
            if worker.ping():
                up = True
                break
            time.sleep(3)
        out["worker_up"] = up
        if up:
            started = worker.call(
                "dev-a",
                "start",
                timeout=240,
                org="dev-a",
                size="custom",
                image="tiny",
                reg="before",
                budget=180000,
            )
            out["start"] = {k: started.get(k) for k in ("accepted", "ready", "ready_ms", "error")}
            if started.get("ready"):
                got = answers_of(worker.call("dev-a", "call", org="dev-a", n=3))
                props = [props_of(a) for a in got]
                out["answers"] = len(got)
                out["props_ok"] = bool(got) and all(p and p.get("orgId") == "dev-a" for p in props)
                worker.call("dev-a", "stop", org="dev-a")
        out["works"] = bool(out.get("props_ok"))
    finally:
        try:
            os.killpg(proc.pid, signal.SIGTERM)
            proc.wait(timeout=30)
        except (ProcessLookupError, subprocess.TimeoutExpired):
            with contextlib.suppress(ProcessLookupError):
                os.killpg(proc.pid, signal.SIGKILL)
        out["log_tail"] = tail(log.read_text(errors="replace"), 8) if log.is_file() else ""
    return out


def decide(du: dict[str, Any]) -> dict[str, Any]:
    """The verdict of Design item 1 and the LIGHT size of Design item 4, from the recorded DU results."""
    d1 = du["DU1"]
    works = d1.get("answered", 0) > 0
    per_instance = (
        works
        and d1.get("cross_answers", 1) == 0
        and d1.get("missing_props", 1) == 0
        and d1.get("distinct_container_ids") == 2
        and d1.get("answered") == d1.get("calls")
        and d1.get("rotated_props_seen") is True
    )
    if per_instance:
        verdict = "GO"
    elif works:
        verdict = "FALLBACK-1"
    elif du.get("public_route", {}).get("reachable"):
        verdict = "FALLBACK-2"
    else:
        verdict = "STOP"
    sizes = du["DU3"]["sizes"]
    idle = du["DU3"]["executor_under_lite"]
    peak = du["DU3"].get("machine_status_peak_mib")
    if sizes["lite"].get("accepted") and peak is not None and peak < 200:
        light = "lite"
    elif sizes["custom"].get("accepted"):
        light = "custom {vcpu: 0.25, memoryMib: 1024, diskMb: 4000}"
    elif sizes["standard-1"].get("accepted"):
        light = "standard-1 (ASKED line needed: about 3.8 times today's memory)"
    else:
        light = "none accepted"
    return {"verdict": verdict, "light": light, "lite_idle_peak_mib": idle.get("idle_peak_mib")}


def run(
    record: pathlib.Path, scratch: pathlib.Path = SCRATCH, skip_dev: bool = False
) -> dict[str, Any]:
    state = load_state(scratch)
    worker = Worker(state["url"], state["key"])
    if not worker.ping():
        raise SpikeError(
            "the scratch Worker at %s does not answer /ping: deploy first" % state["url"]
        )
    executor = bool(state.get("executor_image", True))
    du: dict[str, Any] = {}
    du["DU1"] = prove_du1(worker)
    du["DU7"] = prove_du7(worker)
    du["public_route"] = prove_public_route(worker)

    def redeploy() -> str:
        deploy(version="v2", executor=executor, scratch=scratch, key=state["key"])
        return "v2"

    du["DU2"] = prove_du2(worker, redeploy)
    for o in ("org-a", "org-b"):
        worker.call(o, "stop", org=o)
    du["DU3"] = prove_du3(worker, executor)
    du["DU4"] = {
        "dockerfile": "../../../workers/proxy/Dockerfile",
        "build_context": "../../..",
        "note": "the scratch Worker sits three levels below the repo root, so ../../.. is the plan's ../.. one level up",
        "deployed": executor,
        "image_started": du["DU3"]["executor_under_lite"].get("start", {}).get("ready") is True,
    }
    du["DU6"] = prove_du6(scratch)
    du["DU5"] = {"skipped": True} if skip_dev else prove_du5(scratch)
    result = {
        "worker": WORKER_NAME,
        "ran_at": time.strftime("%Y-%m-%dT%H:%MZ", time.gmtime()),
        "cross_answers": du["DU1"]["cross_answers"],
        "du": du,
        **decide(du),
    }
    record.parent.mkdir(parents=True, exist_ok=True)
    record.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(
        "verdict=%s light=%s cross_answers=%d record=%s"
        % (result["verdict"], result["light"], result["cross_answers"], record)
    )
    return result


def spike_apps(listing: str) -> list[dict[str, Any]]:
    """The container applications of the scratch Worker in `wrangler containers list` output.

    wrangler 4.152 prints a box table (`| ID | NAME | ...`, a 32-hex id); JSON is accepted too. A listing that names the Worker but yields no parsed row is returned as one id-less entry, so a format change fails teardown instead of passing it.
    """
    try:
        data = json.loads(listing)
    except ValueError:
        rows = re.findall(
            r"^\W*([0-9a-f]{32}|[0-9a-f-]{36})\W+(\S*%s\S*)" % WORKER_NAME, listing, re.MULTILINE
        )
        found = [{"id": ident, "name": name} for ident, name in rows]
        if not found and WORKER_NAME in listing:
            return [{"unparsed": True}]
        return found
    items = data if isinstance(data, list) else data.get("result", [])
    return [a for a in items if WORKER_NAME in json.dumps(a)]


def teardown(scratch: pathlib.Path = SCRATCH) -> int:
    """`wrangler delete`, then every container application of the scratch Worker, then a list that must name none."""
    scratch.mkdir(parents=True, exist_ok=True)
    gone = wrangler(["delete", "--name", WORKER_NAME, "--force"], cwd=scratch, timeout=300)
    absent = gone.returncode != 0 and "10090" in (gone.stdout or "") + (gone.stderr or "")
    print(
        "wrangler delete rc=%d%s" % (gone.returncode, " (Worker already absent)" if absent else "")
    )
    if gone.returncode != 0 and not absent:
        print(tail((gone.stdout or "") + (gone.stderr or ""), 6), file=sys.stderr)
    listing = wrangler(["containers", "list"], cwd=scratch, timeout=300)
    if listing.returncode != 0:
        print(
            "wrangler containers list rc=%d\n%s" % (listing.returncode, tail(listing.stderr, 6)),
            file=sys.stderr,
        )
        return 1
    for app in spike_apps(listing.stdout):
        ident = app.get("id")
        if not ident:
            continue
        removed = wrangler(["containers", "delete", str(ident)], cwd=scratch, timeout=300)
        print("wrangler containers delete %s rc=%d" % (str(ident)[:8], removed.returncode))
    after = wrangler(["containers", "list"], cwd=scratch, timeout=300)
    left = spike_apps(after.stdout) if after.returncode == 0 else [{"unknown": True}]
    print("remaining %s applications: %d" % (WORKER_NAME, len(left)))
    state = deploy_state_path(scratch)
    if not left and state.is_file():
        state.unlink()
    return 0 if not left and (gone.returncode == 0 or absent) else 1


def bound() -> bool:
    return PROFILE in (os.environ.get(PROFILES_ENV) or "").split(",")


def reexec(argv: list[str]) -> int:
    """This same run under the deploy-proxy-bench profile; the values reach only the child's environment."""
    env = dict(os.environ)
    env["PYTHONPATH"] = PACKAGE_PARENT + (
        os.pathsep + env["PYTHONPATH"] if env.get("PYTHONPATH") else ""
    )
    cmd = [
        sys.executable, "-m", "rediacc_ci.core.bws_env", "exec", "--profile", PROFILE, "--",
        sys.executable, "-m", SELF, *argv,
    ]  # fmt: skip
    return subprocess.run(cmd, env=env, check=False).returncode


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    parser = argparse.ArgumentParser(prog=SELF, description=(__doc__ or "").splitlines()[0])
    sub = parser.add_subparsers(dest="verb", required=True)
    p_deploy = sub.add_parser(
        "deploy", help="write the scratch Worker and deploy it on workers.dev"
    )
    p_deploy.add_argument("--no-executor", action="store_true", help="omit the real executor image")
    p_run = sub.add_parser("run", help="prove DU1 to DU7 and record the verdict")
    p_run.add_argument("--record", required=True, type=pathlib.Path)
    p_run.add_argument(
        "--skip-dev", action="store_true", help="skip the `wrangler dev` probe (DU5)"
    )
    sub.add_parser("teardown", help="wrangler delete and wrangler containers delete")
    args = parser.parse_args(argv)
    if (
        not os.environ.get("CLOUDFLARE_API_TOKEN")
        and not bound()
        and wrangler_bin() == str(DEFAULT_WRANGLER)
    ):
        return reexec(argv)
    try:
        if args.verb == "deploy":
            deploy(executor=not args.no_executor)
            return 0
        if args.verb == "run":
            run(args.record, skip_dev=args.skip_dev)
            return 0
        return teardown()
    except SpikeError as exc:
        print("%s: %s" % (SELF, exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
