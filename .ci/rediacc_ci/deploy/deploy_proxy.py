class RefusedError(Exception):
    """A run that must stop with exit 1; each line is printed as an error."""

    def __init__(self, *lines: str) -> None:
        super().__init__(lines[0] if lines else "")
        self.lines = lines


# ---- config selection -------------------------------------------------------


def config_key(target: str, region: str) -> str:
    """The proxy_configs target key: `<region>` for stable, `edge-<region>` for edge, `bench` for bench."""
    if target == BENCH_TARGET:
        return "bench"
    return "%s-%s" % (EDGE_TARGET, region) if target == EDGE_TARGET else region


def config_name(target: str, region: str) -> str:
    """`wrangler.<key>.toml`."""
    return "wrangler.%s.toml" % config_key(target, region)


def select(
    repo_root: pathlib.Path, target: str, region: str | None
) -> tuple[proxy_configs.Target, str]:
    """The proxy_configs target and its config text, refused before anything else runs."""
    if target not in SUPPORTED_TARGETS:
        raise RefusedError(
            "--target %s is not supported: only %s deploys."
            % (target, ", ".join(SUPPORTED_TARGETS))
        )
    try:
        regions = proxy_configs.load_regions(repo_root)
        all_targets = proxy_configs.targets(regions)
    except (proxy_configs.ConfigError, KeyError) as exc:
        raise RefusedError("%s: %s" % (SELF, exc)) from None
    region_ids = sorted(str(r.get("id", "")).lower() for r in regions)
    if target == BENCH_TARGET:
        region = region or BENCH_REGION
        if region != BENCH_REGION:
            raise RefusedError(
                "--target bench refuses --region %s: the bench proxy exists only in %s."
                % (region, BENCH_REGION)
            )
    elif not region:
        raise RefusedError(
            "--region is required for --target %s (one of %s)." % (target, ", ".join(region_ids))
        )
    elif region not in region_ids:
        raise RefusedError(
            "--region %s is not supported: regions.json names %s." % (region, ", ".join(region_ids))
        )
    spec = all_targets[config_key(target, region)]
    rel = "%s/%s" % (WORKER_REL, spec.config)
    try:
        text = (repo_root.joinpath(*WORKER_SUBDIR) / spec.config).read_text(encoding="utf-8")
    except OSError as exc:
        raise RefusedError(
            "--target %s refused: %s cannot be read: %s" % (target, rel, exc.strerror or exc)
        ) from None
    reasons = proxy_configs.config_refusals(text, spec, frozenset(region_ids))
    if reasons:
        raise RefusedError(*("--target %s refused: %s: %s" % (target, rel, r) for r in reasons))
    return spec, text


