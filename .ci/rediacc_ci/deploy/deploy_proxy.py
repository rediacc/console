def _run(argv: list[str], *, env: dict[str, str] | None = None) -> int:
    """One child with both streams inherited."""
    return subprocess.run(argv, check=False, env=env).returncode


def _run_tee(argv: list[str]) -> tuple[int, str]:
    """One child whose stdout is copied to this stdout line by line AND kept; stderr inherited."""
    with subprocess.Popen(argv, stdout=subprocess.PIPE, text=True) as proc:
        kept = []
        for line in proc.stdout or ():
            sys.stdout.write(line)
            sys.stdout.flush()
            kept.append(line)
        status = proc.wait()
    return status, "".join(kept)


def _run_capture(argv: list[str]) -> tuple[int, str]:
    proc = subprocess.run(argv, stdout=subprocess.PIPE, text=True, check=False)
    return proc.returncode, proc.stdout


# ---- version ids ------------------------------------------------------------


def parse_version_id(output: str) -> str | None:
    """The id of `Current Version ID: <id>` in wrangler's deploy output (the last one, if several)."""
    found = VERSION_ID_RE.findall(output)
    return found[-1] if found else None


def newest_deployment_version(text: str) -> str | None:
    """The version at 100% in the newest deployment `wrangler deployments list --json` prints; None when there is none or the text is not that shape."""
    try:
        data = json.loads(text)
    except ValueError:
        return None
    if not isinstance(data, list):
        return None
    deployments = [d for d in data if isinstance(d, dict)]
    if not deployments:
        return None
    newest = max(enumerate(deployments), key=lambda p: (str(p[1].get("created_on", "")), p[0]))[1]
    for version in newest.get("versions") or []:
        if isinstance(version, dict) and version.get("percentage") in (100, 100.0):
            return str(version.get("version_id") or "") or None
    return None


def deployed_version(config: str) -> str | None:
    """The newest deployment's 100% version, or None (no deployment yet, or wrangler failed)."""
    status, out = _run_capture(deployments_argv(config))
    return newest_deployment_version(out) if status == 0 else None


# ---- the smoke --------------------------------------------------------------


def curl_argv(url: str, pin: str | None = None) -> list[str]:
    """`curl -sS -o /dev/null -w '%{http_code}' --max-time 30 <url>`, with `--resolve host:443:<pin>` ahead of the URL when a DoH answer pins the address."""
    argv = ["curl", "-sS", "-o", "/dev/null", "-w", "%{http_code}", "--max-time", "30"]
    if pin:
        argv += ["--resolve", "%s:443:%s" % (urllib.parse.urlsplit(url).hostname, pin)]
    return [*argv, url]


def curl_body_argv(url: str, pin: str | None = None) -> list[str]:
    """The same request keeping the body: the body, a newline, then the status code."""
    argv = ["curl", "-sS", "-w", "\\n%{http_code}", "--max-time", "30"]
    if pin:
        argv += ["--resolve", "%s:443:%s" % (urllib.parse.urlsplit(url).hostname, pin)]
    return [*argv, url]


# A brand-new custom domain is often NXDOMAIN on the local resolver for a while: the zone's negative TTL is up to 1800 s, and the first lookup before the record existed is cached. Only a curl "could not resolve host" (exit 6) is retried, for RESOLVE_WINDOW_S seconds; after that the address is read over DNS-over-HTTPS and pinned with `--resolve`. Both are set by the environment so a test (or an operator) can shorten or disable them; an empty `REDIACC_SMOKE_DOH_URL` disables the DoH step.
CURL_RESOLVE_RC = 6
RESOLVE_WINDOW_ENV = "REDIACC_SMOKE_RESOLVE_WINDOW_S"
RESOLVE_INTERVAL_S = 5.0
DEFAULT_RESOLVE_WINDOW_S = "90"
DOH_URL_ENV = "REDIACC_SMOKE_DOH_URL"
DEFAULT_DOH_URL = "https://1.1.1.1/dns-query"
DOH_A_RECORD = 1
DOH_TIMEOUT_S = 10.0


def _resolve_window() -> float:
    """The retry window in seconds; a value that is not a finite number (`inf`, `nan`, text) falls back to the default, since an infinite deadline would retry a persistent exit 6 forever."""
    try:
        value = float(os.environ.get(RESOLVE_WINDOW_ENV, DEFAULT_RESOLVE_WINDOW_S))
    except ValueError:
        return float(DEFAULT_RESOLVE_WINDOW_S)
    return max(0.0, value) if math.isfinite(value) else float(DEFAULT_RESOLVE_WINDOW_S)


def _sleep(seconds: float) -> None:
    time.sleep(seconds)


def _doh_lookup(host: str) -> str | None:
    """The first A record Cloudflare's DoH JSON API holds for `host`, or None (disabled, unreachable, no answer)."""
    base = os.environ.get(DOH_URL_ENV, DEFAULT_DOH_URL)
    if not base:
        return None
    url = "%s?%s" % (base, urllib.parse.urlencode({"name": host, "type": "A"}))
    try:
        request = https.build_request(url, headers={"Accept": "application/dns-json"})
        with https.urlopen(request, timeout=DOH_TIMEOUT_S) as resp:
            body = json.loads(resp.read().decode("utf-8"))
    except (OSError, ValueError):
        return None
    for answer in body.get("Answer") or [] if isinstance(body, dict) else []:
        if isinstance(answer, dict) and answer.get("type") == DOH_A_RECORD and answer.get("data"):
            return str(answer["data"])
    return None


def _curl(url: str, pin: str | None = None) -> tuple[str, int]:
    """curl's stdout (the status code) and exit status; stderr inherited."""
    proc = subprocess.run(curl_argv(url, pin), stdout=subprocess.PIPE, text=True, check=False)
    return proc.stdout, proc.returncode


def _curl_body(url: str, pin: str | None = None) -> tuple[str, str]:
    """(body, status code) of one request; a failed request is ("", curl's code text or "")."""
    proc = subprocess.run(curl_body_argv(url, pin), stdout=subprocess.PIPE, text=True, check=False)
    body, _, code = proc.stdout.rpartition("\n")
    return body, code.strip()


class _Fetcher:
    """Issues the smoke's requests. A resolution failure is retried for the window, then answered by a DoH pin shared by every later request; any other outcome (a code, or another curl failure) returns at once."""

    def __init__(self, host: str) -> None:
        self.host = host
        self.pin: str | None = None

    def code(self, url: str) -> str:
        deadline = time.monotonic() + _resolve_window()
        while True:
            out, rc = _curl(url, self.pin)
            if rc != CURL_RESOLVE_RC:
                return out
            if self.pin is None and time.monotonic() >= deadline:
                address = _doh_lookup(self.host)
                if not address:
                    if os.environ.get(DOH_URL_ENV, DEFAULT_DOH_URL):
                        log.error(
                            "%s does not resolve locally (retried %gs) and DNS-over-HTTPS has no answer for it either; the DNS record may not exist yet"
                            % (self.host, _resolve_window())
                        )
                    else:
                        log.error(
                            "%s does not resolve locally (retried %gs); DNS-over-HTTPS is disabled"
                            % (self.host, _resolve_window())
                        )
                    return out
                log.info(
                    "%s does not resolve locally; DNS-over-HTTPS answers %s, pinning it"
                    % (self.host, address)
                )
                self.pin = address
                return _curl(url, self.pin)[0]
            if self.pin is not None:
                return out
            _sleep(RESOLVE_INTERVAL_S)


def _ready_state(body: str, code: str) -> tuple[bool, str]:
    """(ready, what it said) for one /v1/ready answer."""
    try:
        data = json.loads(body) if body else None
    except ValueError:
        data = None
    if not isinstance(data, dict):
        return False, "status %s, body %r" % (code or "nothing", body[:200])
    if code == "200" and data.get("ready") is True:
        return True, str(data.get("workerVersion") or "")
    return False, "status %s, reason %s" % (code or "nothing", data.get("reason") or "none given")


def wait_ready(
    fetch: _Fetcher, url: str, version_id: str, timing: dict[str, int] | None = None
) -> int:
    """Poll /v1/ready until it answers 200 with `workerVersion == version_id`, for up to READY_TIMEOUT_S. `timing["cold_start_ms"]` gets the wait until that first ready answer."""
    started = time.perf_counter()
    deadline = time.monotonic() + READY_TIMEOUT_S
    last = "no answer"
    while True:
        body, code = _curl_body(url + "/v1/ready", fetch.pin)
        ready, said = _ready_state(body, code)
        if ready and said == version_id:
            if timing is not None:
                timing["cold_start_ms"] = round((time.perf_counter() - started) * 1000)
            return 0
        last = "ready on version %s, not %s" % (said or "(none)", version_id) if ready else said
        if time.monotonic() >= deadline:
            log.error(
                "Smoke test failed: /v1/ready did not answer 200 on version %s within %gs (last: %s)"
                % (version_id, READY_TIMEOUT_S, last)
            )
            return 1
        _sleep(READY_INTERVAL_S)


def smoke(host: str, version_id: str, timing: dict[str, int] | None = None) -> int:
    """The post-deploy smoke: /v1/health 200, an unauthenticated /v1/server-info 401, then /v1/ready on the deployed version."""
    url = "https://" + host
    log.step("Smoke-testing %s..." % url)
    fetch = _Fetcher(host)
    health = fetch.code(url + "/v1/health")
    if health != "200":
        log.error("Smoke test failed: /v1/health answered %s, expected 200" % (health or "nothing"))
        return 1
    info = fetch.code(url + "/v1/server-info")
    if info != "401":
        log.error(
            "Smoke test failed: an unauthenticated /v1/server-info answered %s, expected 401"
            % (info or "nothing")
        )
        return 1
    if wait_ready(fetch, url, version_id, timing) != 0:
        return 1
    log.info(SMOKE_PASSED % version_id)
    return 0


# ---- staging the image ------------------------------------------------------


def stage_bench(repo_root: pathlib.Path, worker_dir: pathlib.Path) -> int:
    """Bench: build the CLI bundle and a DEV-key renet from the tree, then `executor_artifacts stage-local`."""
    log.step("Building the CLI bundle and renet the bench image ships...")
    os.chdir(repo_root)
    for argv in [*(build_argv(w) for w in WORKSPACES), bundle_argv()]:
        status = _run(argv)
        if status != 0:
            return status
    status, out, err = resolve_version.run(["--current"])
    if status != 0:
        sys.stderr.write(err)
        sys.stderr.flush()
        return status
    status = _run(build_renet_argv(repo_root, out.rstrip("\n")), env=package_env())
    if status != 0:
        return status
    return _run(
        artifacts_argv("stage-local", "--dest", str(worker_dir / STAGE_SUBDIR)), env=package_env()
    )


def stage_release(worker_dir: pathlib.Path, version: str) -> int:
    """Stable and edge: fetch and verify the release's executor artifacts."""
    log.step("Fetching the executor artifacts of v%s..." % version)
    return _run(
        artifacts_argv("fetch", "--version", version, "--dest", str(worker_dir / STAGE_SUBDIR)),
        env=package_env(),
    )


# ---- the record -------------------------------------------------------------


def write_record(path: pathlib.Path, record: dict[str, object]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(record, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def read_record_version(path: pathlib.Path | None) -> str | None:
    if path is None or not path.is_file():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    value = data.get("version_id") if isinstance(data, dict) else None
    return str(value) if value else None


def closing_lines(worker: str, version_id: str, rollback: str) -> tuple[str, ...]:
    return (
        "Deployed %s: version %s." % (worker, version_id),
        "Rollback: %s" % rollback,
    )


# ---- main -------------------------------------------------------------------


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog=SELF, description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--target", required=True, help="edge, stable or bench")
    parser.add_argument("--region", default=None, help="eu, us or asia (bench: eu only)")
    parser.add_argument(
        "--version",
        default=None,
        help="the release whose executor artifacts the image is built from",
    )
    parser.add_argument("--record", default=None, help="write the deploy record (JSON) here")
    parser.add_argument(
        "--smoke-only", action="store_true", help="smoke the deployed version without deploying"
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="compile the Worker with wrangler; deploy nothing"
    )
    return parser


def main(argv: list[str]) -> int:
    try:
        args = _parser().parse_args(argv)
    except SystemExit as exc:
        return int(exc.code or 0)

    repo_root = common.repo_root()
    worker_dir = repo_root.joinpath(*WORKER_SUBDIR)
    target = args.target
    bench = target == BENCH_TARGET
    record_path = pathlib.Path(args.record).resolve() if args.record else None

    try:
        spec, _text = select(repo_root, target, args.region)
        region = args.region or BENCH_REGION
        if not bench and not args.dry_run and not args.smoke_only:
            if not args.version:
                raise RefusedError(MISSING_VERSION % target)
            if not VERSION_RE.match(args.version):
                raise RefusedError("--version %r is not a release version (X.Y.Z)" % args.version)
    except RefusedError as exc:
        for line in exc.lines:
            log.error(line)
        return 1
    config = spec.config
    host = spec.routes[0]

    if args.dry_run:
        os.chdir(worker_dir)
        log.step(
            "Dry run: compiling the %s worker without deploying (config: %s)..."
            % (spec.name, config)
        )
        status = _run(dry_run_argv(config))
        if status != 0:
            return status
        log.info("Dry run passed. Nothing was deployed.")
        return 0

    if bench and not profile_bound():
        return _run(reexec_argv(argv), env=package_env())

    if not os.environ.get("CLOUDFLARE_API_TOKEN"):
        if not bench and not profile_bound(PROFILE):
            return _run(reexec_argv(argv, PROFILE), env=package_env())
        print(MISSING_AUTH_MSG, file=sys.stderr, flush=True)
        return 1

    if args.smoke_only:
        os.chdir(worker_dir)
        version_id = read_record_version(record_path) or deployed_version(config)
        if not version_id:
            log.error(
                "--smoke-only: no deployed version of %s to smoke (no record, no deployment)"
                % spec.name
            )
            return 1
        status = smoke(host, version_id)
        if record_path is not None:
            record = {}
            if record_path.is_file():
                try:
                    loaded = json.loads(record_path.read_text(encoding="utf-8"))
                    record = loaded if isinstance(loaded, dict) else {}
                except (OSError, ValueError):
                    record = {}
            record.update({"worker": spec.name, "version_id": version_id, "smoke_rc": status})
            write_record(record_path, record)
        return status

    if bench and not os.environ.get("ACCOUNT_ED25519_PUBLIC_KEY"):
        log.error(MISSING_KEY)
        return 1

    status = (
        stage_bench(repo_root, worker_dir) if bench else stage_release(worker_dir, args.version)
    )
    if status != 0:
        return status

    current_migrations = config_migrations(worker_dir.joinpath(config).read_text(encoding="utf-8"))
    current_tag = migration_tag(current_migrations)
    if bench:
        forward_only = bench_forward_only(
            current_tag, read_record_field(record_path, "migration_tag")
        )
    else:
        forward_only = is_forward_only(
            current_migrations, previous_release_migrations(repo_root, config, args.version)
        )
    os.chdir(worker_dir)
    previous = deployed_version(config)
    log.step("Deploying %s and its container image (config: %s)..." % (spec.name, config))
    status, output = _run_tee(deploy_argv(config))
    if status != 0:
        return status
    version_id = parse_version_id(output)
    if not version_id:
        log.error(
            "wrangler deploy printed no 'Current Version ID:' line; the deployed version is unknown"
        )
        return 1
    listed = deployed_version(config)
    if listed != version_id:
        log.error(
            "wrangler deploy printed version %s, but `wrangler deployments list` names %s at 100%%"
            % (version_id, listed or "no version")
        )
        return 1

    timing: dict[str, int] = {}
    smoke_rc = smoke(host, version_id, timing)
    if forward_only and previous:
        rollback = forward_only_rollback(current_tag or "migration change")
    else:
        rollback = rollback_command(config, previous)
    if record_path is not None:
        write_record(
            record_path,
            {
                "target": target,
                "region": region,
                "worker": spec.name,
                "config": "%s/%s" % (WORKER_REL, config),
                "version_id": version_id,
                "previous_version_id": previous,
                "artifacts_version": None if bench else args.version,
                "smoke_rc": smoke_rc,
                "rollback": rollback,
                "backend": config_var(worker_dir.joinpath(config), "EXECUTOR_BACKEND"),
                "migration_tag": current_tag,
                "cold_start_ms": timing.get("cold_start_ms"),
            },
        )
    if smoke_rc != 0:
        log.error("Rollback: %s" % rollback)
        return smoke_rc
    for line in closing_lines(spec.name, version_id, rollback):
        log.info(line)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
