#!/usr/bin/env python3
"""Deploy the proxy Worker and its executor container image to one target, then prove the deployed version answers.

    PYTHONPATH=.ci python3 -m rediacc_ci.deploy.deploy_proxy --target edge|stable --region eu|us|asia --version V [--record PATH] [--smoke-only] [--dry-run]
    PYTHONPATH=.ci python3 -m rediacc_ci.deploy.deploy_proxy --target bench [--region eu] [--record PATH] [--smoke-only] [--dry-run]

CD DEPLOYS IT (operator order 2026-10-25T18:10Z, agent/plans/PLAN-proxy-cd-six-targets.md). CD runs this module for each of the six targets inside the per-region release job (Design item 9): a deploy run, then `--smoke-only`, and the console executor is switched on only after that smoke passes. Bench stays a separate target run by hand, and deploys to all seven are allowed without asking. The module began as the port of the retired `.ci/scripts/deploy/deploy-proxy.sh`; the bash text stays recoverable through the `twin_blob` of `.ci/rediacc_ci/tests/goldens/twins/deploy.deploy-proxy.jsonl`, whose records are now the port's own answers (re-recorded with `regolden --source port`).

THE CONFIG. `--target` and `--region` pick exactly one file: `workers/proxy/wrangler.<region>.toml` for stable, `wrangler.edge-<region>.toml` for edge, `wrangler.bench.toml` for bench (which refuses any region but eu). The six stable and edge files are generated by `rediacc_ci.deploy.proxy_configs`, and every wrangler call names its file with `--config`. Before any profile, token, fetch or build, `proxy_configs.config_refusals` reads that file and refuses (exit 1, every reason printed) unless it names exactly its own target: the Worker name, the route, ACCOUNT_URL, the ACCOUNT and ISSUER bindings to the same target's account Worker, the telemetry destinations, the key allowlist, no `[env.*]` table, and no token naming another region or channel (a us config carrying an eu binding never reaches a credential).

THE IMAGE IS BUILT FROM FETCHED BYTES. A stable or edge deploy runs `rediacc_ci.deploy.executor_artifacts fetch --version V --dest workers/proxy/stage/`, so the image carries the release's exact CLI bundle and renet, verified by sha256 (Design item 8); `--version` is required. Bench builds the CLI bundle and a renet from the tree, signed for the DEV public key bench licences verify with, and stages them through `executor_artifacts stage-local`. Bench runs under the `deploy-proxy-bench` Bitwarden profile and re-executes itself under it when it is not bound; stable and edge read their credentials from the environment (CD's bws step), and a local run with no `CLOUDFLARE_API_TOKEN` re-executes itself under `bws_env exec --profile deploy-proxy` when that profile is not bound.

THE VERSION ID. `wrangler deploy` output is teed to stdout and the `Current Version ID:` line is captured. `wrangler deployments list --json` must then name that id at 100% in its newest deployment, or the run fails: a deploy whose rollout is not the version it printed is not a deploy this module can vouch for. The newest deployment before the deploy gives the rollback target.

THE SMOKE. `/v1/health` must answer 200, an unauthenticated `/v1/server-info` 401, and `/v1/ready` 200 with `workerVersion` equal to the captured id, polled for up to READY_TIMEOUT_S, because "deploy success means the rollout started" and an old instance may answer first. `--smoke-only` skips the deploy and smokes the version the record (`--record`) names, else the newest deployment's. A fresh custom domain is retried past a cached NXDOMAIN and then pinned through DNS-over-HTTPS.

THE RECORD. `--record PATH` writes JSON: target, region, worker, config, version id, the previous version id, the artifacts version, the smoke rc, the rollback command, the `backend` (`EXECUTOR_BACKEND`), the last `migration_tag` and `cold_start_ms` (the wait for the first `/v1/ready` on the deployed version). A deploy whose `[[migrations]]` list differs from the previous release's (`git show <previous v* tag>:<config>`; bench: its last recorded `migration_tag`) is forward-only, and its rollback reads `forward-only: Durable Object class lifecycle change (v<n>); fix forward` in place of a command wrangler would refuse. The rollback (the deploy record of Design item 9 reads it). The closing lines print the worker, the version id and the rollback command. No executor token is minted, put or named: the Worker obtains one over its ISSUER binding.

A DRY RUN (`--dry-run`) runs the config refusals and `wrangler deploy --dry-run --containers-rollout none` for any target, and needs no credentials, fetch or build. The `none` rollout is load-bearing: wrangler 4.152's dry run DOES build the container image (measured 2026-10-25, it failed on the unstaged `workers/proxy/stage/`), and `none` compiles the Worker without building or updating any container. The image itself is built and booted by check:ci-proxy-image-smoke.
"""

