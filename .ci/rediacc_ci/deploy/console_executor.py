#!/usr/bin/env python3
"""Switch one target's console executor on or off: the account Worker's EXECUTOR_MODE secret (agent/plans/PLAN-proxy-cd-six-targets.md, Design item 2, box D2).

    PYTHONPATH=.ci python3 -m rediacc_ci.deploy.console_executor --enable --target stable --region eu|us|asia
    PYTHONPATH=.ci python3 -m rediacc_ci.deploy.console_executor --disable --target stable|bench [--region eu]

THE SWITCH. EXECUTOR_MODE is never a `[vars]` entry (the account wrangler-config gate refuses one): CD owns it as a Worker secret. `--enable` runs `wrangler secret put EXECUTOR_MODE` with the value `proxy` on wrangler's STDIN, never on argv. `--disable` runs `wrangler secret delete EXECUTOR_MODE`, after which the Worker falls back to its default mode, which a deployed Worker refuses with the coded `CONSOLE_EXECUTION_UNAVAILABLE` 503. A secret survives later account deploys, so a region stays open across releases once its proxy smoke has passed, and CD's rollback step closes it again.

CD runs `--enable` only after that target's proxy smoke passes (operator ruling ASKED:2026-10-25T18:18Z, "Closed until smoke passes"), with `if: steps.proxy_smoke.outcome == 'success'` in .github/workflows/cd-deploy-account.yml.

EVERY SWITCH IS READ BACK. A put or delete that exits 0 is not taken as the answer: `wrangler secret list --format json` must then name EXECUTOR_MODE after an enable and must not name it after a disable. A listing that fails or does not parse is UNKNOWN, and unknown exits 1, because "the region is closed" is a claim this module only makes after reading it. A delete of a secret that was never set fails in wrangler, and the read-back turns that into "already closed" (exit 0), so a disable is idempotent.

A COMPANY (`--company NAME --company-id ID --region R --company-domain D --account-config PATH [--company-bench]`) replaces `--target`: the Enterprise company's own account Worker, named by a config path the caller passes (`workers/account/enterprise.<name>.toml`, generated by the company config step), never a shared `wrangler.<region>.toml`. `company_target` refuses a path that is not that company's file, a Worker name that is not `account-<name>`, a malformed id and an unknown region before anything runs.

THE TARGET. `--target` and `--region` name one account config, `workers/account/wrangler.<region>.toml` for stable (the one shared Worker set of a region) and `wrangler.bench.toml` for bench (eu only); the Worker name is read from that file's `name` and passed to wrangler as `--name` next to `--config`, so the call names its Worker twice and cannot land on another.

ENVIRONMENT. `CLOUDFLARE_API_TOKEN` and `CLOUDFLARE_ACCOUNT_ID`, from CD's Bitwarden step. A bare local call needs the `deploy-proxy` bws profile (bench: `deploy-proxy-bench`): when either variable is unset and that profile is not bound, the run re-executes itself under `bws_env exec --profile <profile>`, so no wrapper is typed.
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import os
import pathlib
import re
import subprocess
import sys
import tomllib
import typing

from rediacc_ci import log, paths
from rediacc_ci.core import wrangler
from rediacc_ci.enterprise import names

SELF = "rediacc_ci.deploy.console_executor"

MODE_KEY = "EXECUTOR_MODE"
MODE_VALUE = "proxy"

STABLE_TARGET = "stable"
BENCH_TARGET = "bench"
TARGETS = (STABLE_TARGET, BENCH_TARGET)
BENCH_REGION = "eu"

ACCOUNT_SUBDIR = ("workers", "account")
ACCOUNT_REL = "/".join(ACCOUNT_SUBDIR)

PROFILE = "deploy-proxy"
BENCH_PROFILE = "deploy-proxy-bench"
PACKAGE_PARENT = str(paths.repo_root() / ".ci")


def profile_for(target: str) -> str:
    return BENCH_PROFILE if target == BENCH_TARGET else PROFILE


def missing_env() -> list[str]:
    """The required variables that are unset or empty, read by name."""
    missing = []
    if not os.environ.get("CLOUDFLARE_API_TOKEN"):
        missing.append("CLOUDFLARE_API_TOKEN")
    if not os.environ.get("CLOUDFLARE_ACCOUNT_ID"):
        missing.append("CLOUDFLARE_ACCOUNT_ID")
    return missing


def profile_bound(profile: str) -> bool:
    carried = (item.strip() for item in (os.environ.get("REDIACC_BWS_PROFILES") or "").split(","))
    return profile in carried


def reexec_argv(profile: str, argv: list[str], module: str = SELF) -> list[str]:
    """This same run (or `module`'s, for a caller sharing the re-exec) under one bws profile."""
    return [
        sys.executable,
        "-m",
        "rediacc_ci.core.bws_env",
        "exec",
        "--profile",
        profile,
        "--",
        sys.executable,
        "-m",
        module,
        *argv,
    ]


def package_env() -> dict[str, str]:
    """The child environment with this checkout's `.ci` first on PYTHONPATH."""
    env = dict(os.environ)
    existing = env.get("PYTHONPATH")
    env["PYTHONPATH"] = PACKAGE_PARENT + (os.pathsep + existing if existing else "")
    return env


class RefusedError(Exception):
    """A run that must stop with exit 1; the message is printed as an error."""


COMPANY_ID_RE = re.compile(r"^c[0-9a-f]{8,}$")
DOMAIN_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*(?:\.[a-z0-9]+(?:-[a-z0-9]+)*)+$")
PROXY_SUBDIR = ("workers", "proxy")


def mask_label(text: str, name: str, company_id: str) -> str:
    """`text` with every occurrence of the company label replaced by its opaque id, joined to other characters or not (a Worker, config or host name built from it, `acmecorpdb` included: review a55df887.3). Log lines go through this, so only the id reaches a console; masking a few extra characters is harmless, leaking the label is not."""
    return re.sub(re.escape(name), company_id, text, flags=re.IGNORECASE)


@dataclasses.dataclass(frozen=True)
class CompanyTarget:
    """One Enterprise company as a deploy target: identity and config paths, all parameters.

    `name` is the company label (Worker and host names), `company_id` the opaque `c<hex>` id the control database and any public surface carry. The two config paths come from the company config generator (box N4); this module never imports it.
    """

    name: str
    company_id: str
    region: str
    domain: str
    account_config: pathlib.Path | None = None
    proxy_config: pathlib.Path | None = None
    bench: bool = False

    def mask(self, text: str) -> str:
        """`text` for a log line: the label becomes the opaque id."""
        return mask_label(text, self.name, self.company_id)

    @property
    def account_worker(self) -> str:
        return "account-%s" % self.name

    @property
    def proxy_worker(self) -> str:
        return "proxy-%s" % self.name

    @property
    def hosts(self) -> tuple[str, str]:
        return names.hosts(self.name, self.domain)

    @property
    def profile_target(self) -> str:
        """The shared target whose credentials profile and staging rules a company deploy follows."""
        return BENCH_TARGET if self.bench else STABLE_TARGET


def _company_config(
    path: pathlib.Path | None, subdir: tuple[str, ...], worker: str, name: str, root: pathlib.Path
) -> pathlib.Path | None:
    if path is None:
        return None
    path = pathlib.Path(path)
    want = "enterprise.%s.toml" % name
    if path.name != want:
        raise RefusedError(
            "%s is not this company's config: a company deploy takes %s, never a shared config"
            % (path, want)
        )
    folder = root.joinpath(*subdir).resolve()
    if path.resolve().parent != folder:
        raise RefusedError("%s is not under %s" % (path, "/".join(subdir)))
    try:
        doc = tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise RefusedError("%s cannot be read: %s" % (path, exc)) from None
    if doc.get("name") != worker:
        raise RefusedError("%s names the Worker %r, not %r" % (path, doc.get("name"), worker))
    return path.resolve()


def company_target(
    repo_root: pathlib.Path,
    *,
    name: str,
    company_id: str,
    region: str,
    domain: str,
    account_config: pathlib.Path | None = None,
    proxy_config: pathlib.Path | None = None,
    bench: bool = False,
) -> CompanyTarget:
    """A validated company target; raises RefusedError naming the first rule broken."""
    try:
        names.check(name)
    except names.CompanyNameError as exc:
        raise RefusedError("--company refused: %s" % exc) from None
    if not isinstance(company_id, str) or not COMPANY_ID_RE.fullmatch(company_id):
        raise RefusedError("--company-id is not an opaque id (c followed by 8 or more hex digits)")
    known = region_ids(repo_root)
    if region not in known:
        raise RefusedError("--region %s is not one of %s" % (region or "(none)", ", ".join(known)))
    if not isinstance(domain, str) or not DOMAIN_RE.fullmatch(domain):
        raise RefusedError("--company-domain %r is not a host domain" % (domain,))
    if bench and region != BENCH_REGION:
        raise RefusedError(
            "--company-bench refuses --region %s (bench is %s only)" % (region, BENCH_REGION)
        )
    try:
        account_path = _company_config(
            account_config, ACCOUNT_SUBDIR, "account-%s" % name, name, repo_root
        )
        proxy_path = _company_config(proxy_config, PROXY_SUBDIR, "proxy-%s" % name, name, repo_root)
    except RefusedError as exc:
        # A refusal names the config it read, and the config name carries the label.
        raise RefusedError(mask_label(str(exc), name, company_id)) from None
    return CompanyTarget(
        name=name,
        company_id=company_id,
        region=region,
        domain=domain,
        account_config=account_path,
        proxy_config=proxy_path,
        bench=bench,
    )


COMPANY_FLAGS = (
    "company_id",
    "company_domain",
    "account_config",
    "proxy_config",
    "company_bench",
)


def add_company_arguments(parser: argparse.ArgumentParser) -> None:
    """The company flags every deploy module's parser shares."""
    parser.add_argument("--company", default=None, help="an Enterprise company (replaces --target)")
    parser.add_argument("--company-id", default=None, help="the company's opaque c<hex> id")
    parser.add_argument("--company-domain", default=None, help="the product domain of its hosts")
    parser.add_argument("--account-config", default=None, help="the company's account config path")
    parser.add_argument("--proxy-config", default=None, help="the company's proxy config path")
    parser.add_argument("--company-bench", action="store_true", help="a bench company")


def company_from_values(
    repo_root: pathlib.Path, values: typing.Mapping[str, typing.Any], region: str | None
) -> CompanyTarget | None:
    """The company a flag set names, None when no `company` is given; a company flag without it is refused."""
    if not values.get("company"):
        stray = [f for f in COMPANY_FLAGS if values.get(f)]
        if stray:
            raise RefusedError("--%s needs --company" % stray[0].replace("_", "-"))
        return None
    missing = [f for f in ("company_id", "company_domain") if not values.get(f)]
    if missing or not region:
        need = ["--" + f.replace("_", "-") for f in missing] + ([] if region else ["--region"])
        raise RefusedError("--company also needs %s" % ", ".join(need))
    return company_target(
        repo_root,
        name=str(values["company"]),
        company_id=str(values["company_id"]),
        region=region,
        domain=str(values["company_domain"]),
        account_config=pathlib.Path(values["account_config"])
        if values.get("account_config")
        else None,
        proxy_config=pathlib.Path(values["proxy_config"]) if values.get("proxy_config") else None,
        bench=bool(values.get("company_bench")),
    )


def company_argv(company: CompanyTarget) -> list[str]:
    """The flags that name this company again in a child deploy command."""
    argv = [
        "--company",
        company.name,
        "--company-id",
        company.company_id,
        "--region",
        company.region,
        "--company-domain",
        company.domain,
    ]
    if company.account_config is not None:
        argv += ["--account-config", str(company.account_config)]
    if company.proxy_config is not None:
        argv += ["--proxy-config", str(company.proxy_config)]
    if company.bench:
        argv.append("--company-bench")
    return argv


def account_config(target: str, region: str) -> str:
    """The account wrangler config file name for one target."""
    if target == BENCH_TARGET:
        return "wrangler.bench.toml"
    return "wrangler.%s.toml" % region


def region_ids(repo_root: pathlib.Path) -> list[str]:
    """The region ids regions.json names."""
    try:
        doc = json.loads((repo_root / "regions.json").read_text(encoding="utf-8"))
        return sorted(str(r["id"]).lower() for r in doc["regions"])
    except (OSError, ValueError, KeyError, TypeError) as exc:
        raise RefusedError("%s: regions.json cannot be read: %s" % (SELF, exc)) from None


def resolve_target(repo_root: pathlib.Path, target: str, region: str | None) -> tuple[str, str]:
    """(region, config file name) for a valid target, refused otherwise."""
    if target not in TARGETS:
        raise RefusedError("--target %s is not one of %s" % (target, ", ".join(TARGETS)))
    if target == BENCH_TARGET:
        region = region or BENCH_REGION
        if region != BENCH_REGION:
            raise RefusedError(
                "--target bench refuses --region %s: bench exists only in %s"
                % (region, BENCH_REGION)
            )
    else:
        known = region_ids(repo_root)
        if not region or region not in known:
            raise RefusedError(
                "--region %s is not one of %s" % (region or "(none)", ", ".join(known))
            )
    return region, account_config(target, region)


def worker_name(config_path: pathlib.Path) -> str:
    """The `name` of one wrangler config."""
    try:
        doc = tomllib.loads(config_path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise RefusedError("%s cannot be read: %s" % (config_path, exc)) from None
    name = doc.get("name")
    if not isinstance(name, str) or not name:
        raise RefusedError("%s has no top-level `name`" % config_path)
    return name


def put_argv(worker: str, config: str) -> list[str]:
    return [*wrangler.ARGV, "secret", "put", MODE_KEY, "--name", worker, "--config", config]


def delete_argv(worker: str, config: str) -> list[str]:
    return [*wrangler.ARGV, "secret", "delete", MODE_KEY, "--name", worker, "--config", config]


def list_argv(worker: str, config: str) -> list[str]:
    return [
        *wrangler.ARGV,
        "secret",
        "list",
        "--name",
        worker,
        "--format",
        "json",
        "--config",
        config,
    ]


def secret_names(text: str) -> set[str] | None:
    """The secret names a `wrangler secret list --format json` answer holds; None when the text is not that shape.

    The JSON array is read from the first `[` to the last `]`, so a banner line wrangler prints ahead of it does not make a good answer unreadable.
    """
    start, end = text.find("["), text.rfind("]")
    if start < 0 or end < start:
        return None
    try:
        data = json.loads(text[start : end + 1])
    except ValueError:
        return None
    if not isinstance(data, list):
        return None
    names = set()
    for entry in data:
        if not isinstance(entry, dict) or not isinstance(entry.get("name"), str):
            return None
        names.add(entry["name"])
    return names


def _run(argv: list[str], cwd: pathlib.Path, stdin_text: str | None) -> int:
    """One wrangler child, both streams inherited. `stdin_text` None gives it /dev/null, so wrangler takes its non-interactive path and confirms nothing."""
    if stdin_text is None:
        return subprocess.run(argv, cwd=cwd, stdin=subprocess.DEVNULL, check=False).returncode
    return subprocess.run(argv, cwd=cwd, input=stdin_text, text=True, check=False).returncode


def _list(worker: str, config: str, cwd: pathlib.Path) -> set[str] | None:
    proc = subprocess.run(
        list_argv(worker, config),
        cwd=cwd,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        text=True,
        check=False,
    )
    return secret_names(proc.stdout) if proc.returncode == 0 else None


def run(
    action: str,
    target: str,
    region: str | None,
    repo_root: pathlib.Path | None = None,
    argv: list[str] | None = None,
    company: CompanyTarget | None = None,
) -> int:
    """Enable or disable one target's console executor and read the result back. Returns the exit status.

    A `company` replaces `target`: its own account config, in its own directory, names the Worker."""
    root = repo_root or paths.repo_root()
    try:
        if company is not None:
            if company.account_config is None:
                raise RefusedError("--company needs --account-config for the console executor")
            target, region = company.profile_target, company.region
            worker_dir, config = company.account_config.parent, company.account_config.name
            worker = worker_name(company.account_config)
        else:
            region, config = resolve_target(root, target, region)
            worker_dir = root.joinpath(*ACCOUNT_SUBDIR)
            worker = worker_name(worker_dir / config)
    except RefusedError as exc:
        log.error(company.mask(str(exc)) if company is not None else str(exc))
        return 1
    missing = missing_env()
    if missing:
        profile = profile_for(target)
        if argv is not None and not profile_bound(profile):
            return subprocess.run(
                reexec_argv(profile, argv), check=False, env=package_env()
            ).returncode
        log.error(
            "%s must be set (CD's Bitwarden step, or bws_env exec --profile %s)"
            % (" and ".join(missing), profile)
        )
        return 1

    # Log lines call a company's Worker by its id: the Worker name carries the label.
    shown = company.mask(worker) if company is not None else worker
    if company is not None:
        where = "%s (company %s, %s)" % (shown, company.company_id, region)
    else:
        where = "%s (%s %s, %s/%s)" % (worker, target, region, ACCOUNT_REL, config)
    if action == "enable":
        log.step("Opening the console executor on %s: %s=%s..." % (where, MODE_KEY, MODE_VALUE))
        status = _run(put_argv(worker, config), worker_dir, MODE_VALUE)
        if status != 0:
            log.error("wrangler secret put %s exited %d on %s" % (MODE_KEY, status, shown))
            return status
        names = _list(worker, config, worker_dir)
        if names is None:
            log.error(
                "UNVERIFIED: wrangler secret list on %s failed or did not parse, so %s cannot be read back"
                % (shown, MODE_KEY)
            )
            return 1
        if MODE_KEY not in names:
            log.error(
                "wrangler secret put exited 0 but %s does not list %s (%d secrets listed)"
                % (shown, MODE_KEY, len(names))
            )
            return 1
        log.info(
            "Console executor OPEN on %s: %s listed among %d secrets."
            % (where, MODE_KEY, len(names))
        )
        return 0

    log.step("Closing the console executor on %s: deleting %s..." % (where, MODE_KEY))
    status = _run(delete_argv(worker, config), worker_dir, None)
    names = _list(worker, config, worker_dir)
    if names is None:
        log.error(
            "UNVERIFIED: wrangler secret list on %s failed or did not parse, so the region is not known to be closed"
            % shown
        )
        return 1
    if MODE_KEY in names:
        log.error(
            "%s still lists %s after wrangler secret delete (exit %d): the region is OPEN"
            % (shown, MODE_KEY, status)
        )
        return 1
    if status != 0:
        log.info("%s was not set on %s; the region was already closed." % (MODE_KEY, shown))
    log.info(
        "Console executor CLOSED on %s: %s absent among %d secrets." % (where, MODE_KEY, len(names))
    )
    return 0


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog=SELF, description=(__doc__ or "").splitlines()[0])
    switch = parser.add_mutually_exclusive_group(required=True)
    switch.add_argument("--enable", action="store_true", help="put EXECUTOR_MODE=proxy")
    switch.add_argument("--disable", action="store_true", help="delete EXECUTOR_MODE")
    parser.add_argument("--target", default=None, help="stable or bench")
    parser.add_argument("--region", default=None, help="eu, us or asia (bench: eu only)")
    add_company_arguments(parser)
    return parser


def main(argv: list[str]) -> int:
    parser = _parser()
    try:
        args = parser.parse_args(argv)
        if args.company is None and args.target is None:
            parser.error("the following arguments are required: --target")
    except SystemExit as exc:
        return int(exc.code or 0)
    action = "enable" if args.enable else "disable"
    try:
        company = company_from_values(paths.repo_root(), vars(args), args.region)
        if company is not None and args.target is not None:
            raise RefusedError("--company replaces --target; give one")
    except RefusedError as exc:
        log.error(str(exc))
        return 1
    return run(action, args.target or "", args.region, argv=argv, company=company)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
