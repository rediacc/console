"""`./run.sh legal-entity sync|verify` -- the contracting entity, projected from the vault and verified against it.

THE SOURCE. The contracting entity is ten SEPARATE vault entries: the nine invoice fields (SELLER_NAME, SELLER_REGISTRATION_NUMBER, SELLER_VAT_NUMBER, SELLER_ADDRESS_LINE1, SELLER_ADDRESS_LINE2, SELLER_CITY, SELLER_POSTAL_CODE, SELLER_COUNTRY, SELLER_EMAIL) plus SELLER_REGISTER_NAME. The `legal-entity` profile in `.ci/config/secret-supply.json` requires all ten, so a sync or a verify never sees a partial record. The invoice seller and the party to the Terms of Service are one entity, so there is no second record (operator ruling R1, agent/plans/PLAN-terms-acceptance.md Design 1).

THE PROJECTION. `sync` writes `packages/shared/src/legal/entity.generated.json` (sorted keys) and `entity.generated.ts` (`LEGAL_ENTITY`). Builds without the vault (PR lanes, local dev, unit tests) build from these committed files, which are the last copy a release verified, so no placeholder exists and none can ship. SELLER_EMAIL is not projected: WK_CONTACT_EMAIL stays the legal contact. It is still inside `sourceSha256`, the sha256 of the canonical JSON of all ten vault values, so any vault edit makes `verify` fail until `sync` and a commit follow. The country is stored as its ISO code only; each locale renders the name.

FAIL CLOSED WHERE THE VAULT IS REACHABLE. `verify` re-reads the vault, recomputes the projection and compares it with the committed files field by field. It prints FIELD NAMES, never values, and exits 1 on any difference, on a missing entry and when the vault cannot be reached. The release-local step `legal-entity-verify` and the account and www deploy workflows run it before a build.

NO VALUE REACHES A STREAM. Every message names a field or a file. The values exist in this process's environment (bound by `bws_env exec`) and in the two committed files, and nowhere else.
"""

from __future__ import annotations

import hashlib
import json
import os
import subprocess
import sys
import typing

from rediacc_ci import paths

if typing.TYPE_CHECKING:
    import pathlib
    from collections.abc import Callable, Mapping, Sequence

NAME = "rediacc_ci.legal.entity"
PROFILE = "legal-entity"
PROFILES_ENV = "REDIACC_BWS_PROFILES"

# Vault entry -> projected key. SELLER_EMAIL maps to None: hashed, never projected.
FIELDS: tuple[tuple[str, str | None], ...] = (
    ("SELLER_NAME", "legalName"),
    ("SELLER_REGISTRATION_NUMBER", "registryCode"),
    ("SELLER_REGISTER_NAME", "registerName"),
    ("SELLER_VAT_NUMBER", "vatNumber"),
    ("SELLER_ADDRESS_LINE1", "addressLine1"),
    ("SELLER_ADDRESS_LINE2", "addressLine2"),
    ("SELLER_CITY", "city"),
    ("SELLER_POSTAL_CODE", "postalCode"),
    ("SELLER_COUNTRY", "countryCode"),
    ("SELLER_EMAIL", None),
)
VAULT_NAMES: tuple[str, ...] = tuple(name for name, _key in FIELDS)

JSON_REL = ("packages", "shared", "src", "legal", "entity.generated.json")
TS_REL = ("packages", "shared", "src", "legal", "entity.generated.ts")

TS_BANNER = (
    "// AUTO-GENERATED by `./run.sh legal-entity sync` (.ci/rediacc_ci/legal/entity.py) - DO NOT EDIT\n"
    "// Source: the ten SELLER_* vault entries the `legal-entity` profile binds; `./run.sh legal-entity verify` holds this file equal to them before every release and Worker deploy.\n"
)

USAGE = """usage: ./run.sh legal-entity sync|verify

  sync    read the ten SELLER_* vault entries (profile legal-entity) and write
          packages/shared/src/legal/entity.generated.{json,ts}
  verify  compare the committed projection with the vault; print the names of
          the fields that differ, never a value; exit 1 on any difference, on a
          missing entry, or when the vault cannot be reached
"""


class EntityError(Exception):
    """A refusal whose message names fields or files, never a value."""


def read_vault(env: Mapping[str, str]) -> dict[str, str]:
    """The ten vault values from ENV. A missing or empty entry is refused by name."""
    missing = [name for name in VAULT_NAMES if not env.get(name, "")]
    if missing:
        raise EntityError(
            "%d vault entr%s missing or empty: %s (profile %s requires all ten)"
            % (len(missing), "y is" if len(missing) == 1 else "ies are", " ".join(missing), PROFILE)
        )
    return {name: env[name] for name in VAULT_NAMES}


def source_sha256(vault: Mapping[str, str]) -> str:
    """sha256 of the canonical JSON (sorted keys, no whitespace, UTF-8) of the ten vault values."""
    canonical = json.dumps(
        {name: vault[name] for name in VAULT_NAMES},
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def registered_address(projection: Mapping[str, str]) -> str:
    """The registered address without the country, in the order the Estonian register writes it: county and city, district, street, postal code. Each locale appends its own rendering of `countryCode`."""
    parts = (
        projection["city"],
        projection["addressLine2"],
        projection["addressLine1"],
        projection["postalCode"],
    )
    return ", ".join(p for p in parts if p)


def project(vault: Mapping[str, str]) -> dict[str, str]:
    """The projection, sorted keys: the nine projected fields, `registeredAddress` and `sourceSha256`."""
    out = {key: vault[name] for name, key in FIELDS if key is not None}
    country = out["countryCode"]
    if len(country) != 2 or not country.isalpha() or not country.isupper():
        raise EntityError(
            "SELLER_COUNTRY is not an ISO 3166-1 alpha-2 code (two upper-case letters); fix the vault entry"
        )
    out["registeredAddress"] = registered_address(out)
    out["sourceSha256"] = source_sha256(vault)
    return dict(sorted(out.items()))


def render_json(projection: Mapping[str, str]) -> str:
    return json.dumps(dict(sorted(projection.items())), indent=2, ensure_ascii=False) + "\n"


def _ts_string(value: str) -> str:
    """A TypeScript string literal in the formatter's preferred quote: single, unless the value holds a single quote and no double quote."""
    if "'" in value and '"' not in value:
        return json.dumps(value, ensure_ascii=False)
    escaped = value.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n")
    return "'%s'" % escaped


def render_ts(projection: Mapping[str, str]) -> str:
    body = "".join(
        "  %s: %s,\n" % (key, _ts_string(value)) for key, value in sorted(projection.items())
    )
    return (
        TS_BANNER
        + "\nexport const LEGAL_ENTITY = {\n"
        + body
        + "} as const;\n\nexport type LegalEntity = typeof LEGAL_ENTITY;\n"
    )


def _path(root: pathlib.Path, rel: Sequence[str]) -> pathlib.Path:
    return root.joinpath(*rel)


def sync(env: Mapping[str, str], root: pathlib.Path) -> int:
    projection = project(read_vault(env))
    json_path = _path(root, JSON_REL)
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(render_json(projection), encoding="utf-8")
    _path(root, TS_REL).write_text(render_ts(projection), encoding="utf-8")
    print(
        "%s: wrote %s and %s (%d field(s))"
        % (
            NAME,
            "/".join(JSON_REL),
            "/".join(TS_REL),
            len(projection),
        )
    )
    return 0


def drift(env: Mapping[str, str], root: pathlib.Path) -> list[str]:
    """The problems, each naming a field or a file and never a value. Empty means the committed projection equals the vault."""
    want = project(read_vault(env))
    json_path = _path(root, JSON_REL)
    try:
        have = json.loads(json_path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return ["%s is missing; run ./run.sh legal-entity sync" % "/".join(JSON_REL)]
    except json.JSONDecodeError:
        return ["%s does not parse as JSON; run ./run.sh legal-entity sync" % "/".join(JSON_REL)]
    if not isinstance(have, dict):
        return ["%s is not a JSON object; run ./run.sh legal-entity sync" % "/".join(JSON_REL)]
    problems = [
        "field %s differs from the vault" % key
        for key in sorted(set(want) | set(have))
        if want.get(key) != have.get(key)
    ]
    ts_path = _path(root, TS_REL)
    try:
        ts_text = ts_path.read_text(encoding="utf-8")
    except FileNotFoundError:
        ts_text = None
    if ts_text != render_ts(want):
        problems.append("%s differs from the render of the vault" % "/".join(TS_REL))
    return problems


def verify(env: Mapping[str, str], root: pathlib.Path) -> int:
    problems = drift(env, root)
    if problems:
        print(
            "%s: the committed projection trails the vault (%d problem(s)):"
            % (NAME, len(problems)),
            file=sys.stderr,
        )
        for line in problems:
            print("  " + line, file=sys.stderr)
        print(
            "  run ./run.sh legal-entity sync and commit the two files; no release or Worker deploy goes out while they trail the vault",
            file=sys.stderr,
        )
        return 1
    print(
        "%s: the committed projection equals the vault (%d vault entries)"
        % (NAME, len(VAULT_NAMES))
    )
    return 0


def _hydrated(env: Mapping[str, str]) -> bool:
    return PROFILE in env.get(PROFILES_ENV, "").split(",")


def reexec_argv(sub: str) -> list[str]:
    return [
        sys.executable,
        "-m",
        "rediacc_ci.core.bws_env",
        "exec",
        "--profile",
        PROFILE,
        "--",
        sys.executable,
        "-m",
        NAME,
        sub,
    ]


def _run_child(argv: list[str], env: dict[str, str]) -> int:
    return subprocess.run(argv, env=env, check=False).returncode


def main(
    argv: Sequence[str] | None = None,
    *,
    env: Mapping[str, str] | None = None,
    root: pathlib.Path | None = None,
    run_child: Callable[[list[str], dict[str, str]], int] = _run_child,
) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if len(args) != 1 or args[0] not in ("sync", "verify"):
        sys.stderr.write(USAGE)
        return 2
    sub = args[0]
    environ = dict(os.environ if env is None else env)
    if not _hydrated(environ):
        # Re-run under the profile. bws_env binds the ten entries into the child's ENVIRONMENT, never a file; a refusal (no token, an absent entry, an unreachable store) is its non-zero exit, which is a verify failure, not a pass.
        ci = str(paths.ci_dir())
        existing = environ.get("PYTHONPATH", "")
        environ["PYTHONPATH"] = ci + (":" + existing if existing else "")
        rc = run_child(reexec_argv(sub), environ)
        if rc != 0:
            print(
                "%s: %s failed under profile %s (exit %d): the vault was not reached or an entry is absent, which is a failure and never a pass"
                % (NAME, sub, PROFILE, rc),
                file=sys.stderr,
            )
            return 1
        return 0
    base = paths.repo_root() if root is None else root
    try:
        return sync(environ, base) if sub == "sync" else verify(environ, base)
    except EntityError as exc:
        print("%s: %s" % (NAME, exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
