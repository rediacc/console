"""A company's two Worker configs, generated from the templates and held to the proxy gate's refusals.

`generate(company, region, d1_id)` fills `workers/proxy/wrangler.template.toml` (through `proxy_configs.company_target` and `render`, so the shared output stays byte-identical) and `workers/account/enterprise.template.toml`, then runs `proxy_configs.config_refusals` and `account_refusals` plus the company's own account checks over the result and raises `ConfigError` naming each refusal. `write` puts the two texts at gitignored `workers/{proxy,account}/enterprise.<company>.toml`, a name that escapes `proxy_configs.CONFIG_GLOB`, so `check:ci-proxy-configs` never reads a company file and no company name reaches a tracked path.

The host names come from `well_known.PRODUCT_DOMAIN` and regions.json, never typed here. The account config carries no signing secret name: a company Worker reaches its region's signer by binding (S2-S4), and holds neither the private key nor `FREE_LICENSE_HMAC_KEY`.
"""

from __future__ import annotations

import re
import tomllib
import typing

from rediacc_ci import paths
from rediacc_ci.deploy import proxy_configs as pc
from rediacc_ci.enterprise import names
from rediacc_ci.well_known import PRODUCT_DOMAIN

if typing.TYPE_CHECKING:
    import pathlib

ACCOUNT_TEMPLATE = "enterprise.template.toml"
D1_ID_RE = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")
# Names a company account config may never carry: the licence signing key and the FREE licence HMAC key stay off every production account Worker.
SIGNING_NAMES = ("ED25519_PRIVATE_KEY", "FREE_LICENSE_HMAC_KEY", "LICENSE_SIGNING")
HEADER = (
    "GENERATED by rediacc_ci.enterprise.configs from enterprise.template.toml and regions.json;"
    " gitignored, never edited by hand."
)


class ConfigError(Exception):
    """The company, region or id cannot produce configs, or the output is refused."""


class Generated(typing.NamedTuple):
    proxy: str
    account: str


def _root(root: pathlib.Path | None) -> pathlib.Path:
    return root if root is not None else paths.repo_root()


def _region(region: str, root: pathlib.Path) -> tuple[list[dict], dict]:
    try:
        regions = pc.load_regions(root)
    except pc.ConfigError as exc:
        raise ConfigError(str(exc)) from None
    for entry in regions:
        if str(entry.get("id")) == region:
            return regions, entry
    raise ConfigError(
        "no region %r; the regions are %s" % (region, ", ".join(str(r["id"]) for r in regions))
    )


def _check_allow_ips(allow_ips: tuple[str, ...]) -> tuple[tuple[str, str], ...]:
    if not allow_ips:
        return ()
    # Each entry is stripped before it is joined, so the checked text is the emitted text.
    value = ",".join(entry.strip() for item in allow_ips for entry in item.split(","))
    reason = pc.allow_ips_refusal(value)
    if reason:
        raise ConfigError(reason)
    return (("ALLOW_IPS", value),)


def proxy_refusals(
    company: str, region: str, text: str, *, root: pathlib.Path | None = None
) -> list[str]:
    """Why `text` may not stand as the company's proxy config; empty when it may."""
    root = _root(root)
    regions, _ = _region(region, root)
    target = pc.company_target(company, region, regions, PRODUCT_DOMAIN)
    return pc.config_refusals(text, target, pc._region_tokens(regions))


def account_refusals(
    company: str, region: str, text: str, *, root: pathlib.Path | None = None
) -> list[str]:
    """Why `text` may not stand as the company's account config; empty when it may."""
    root = _root(root)
    regions, entry = _region(region, root)
    all_regions = pc._region_tokens(regions)
    own = frozenset({region})
    out = pc.account_refusals(text, "proxy-%s" % company, company, all_regions, own)
    try:
        config = tomllib.loads(text)
    except tomllib.TOMLDecodeError:
        return out
    host = "%s.%s" % (company, PRODUCT_DOMAIN)
    foreign = (all_regions | pc.CHANNEL_TOKENS) - own

    def want(label: str, got: object, expected: object) -> None:
        if got != expected:
            out.append("%s is %r, not %r" % (label, got, expected))

    want("name", config.get("name"), "account-%s" % company)
    for token in pc.NAME_TOKEN_SPLIT.split(str(config.get("name", "")).lower()):
        if token in foreign:
            out.append("name %r names %s, which is not %s" % (config.get("name"), token, company))
    want("routes", config.get("routes"), [{"pattern": host + "/*", "zone_name": PRODUCT_DOMAIN}])
    variables = config.get("vars") or {}
    want("vars.REGION", variables.get("REGION"), region)
    want("vars.WEBAUTHN_RP_ID", variables.get("WEBAUTHN_RP_ID"), host)
    want("vars.WEBAUTHN_ORIGIN", variables.get("WEBAUTHN_ORIGIN"), "https://" + host)
    out.extend(
        "vars.%s is not one a company account config may carry" % key
        for key in sorted(
            set(variables)
            - {"REGION", "ENVIRONMENT", "WEBAUTHN_RP_ID", "WEBAUTHN_ORIGIN", "ALLOW_IPS"}
        )
    )
    if "ALLOW_IPS" in variables:
        reason = pc.allow_ips_refusal(variables["ALLOW_IPS"])
        if reason:
            out.append(reason)
    d1 = [d.get("database_name") for d in config.get("d1_databases") or []]
    want("d1 database names", d1, ["account-%s" % company])
    buckets = [b.get("bucket_name") for b in config.get("r2_buckets") or []]
    want("r2 bucket names", buckets, ["configs-%s" % company, "backups-%s" % company])
    jurisdiction = entry.get("r2Jurisdiction")
    for bucket in config.get("r2_buckets") or []:
        if bucket.get("jurisdiction") != jurisdiction:
            out.append(
                "bucket %r jurisdiction is %r, not %r"
                % (bucket.get("bucket_name"), bucket.get("jurisdiction"), jurisdiction)
            )
    queues = [q.get("queue") for q in (config.get("queues") or {}).get("producers") or []]
    want("queue producers", queues, ["backup-replicate-%s" % company])
    out.extend(
        "the text names %s; a company account Worker never holds it" % marker
        for marker in SIGNING_NAMES
        if marker in text
    )
    return out


def generate(
    company: str,
    region: str,
    d1_id: str,
    *,
    allow_ips: tuple[str, ...] = (),
    root: pathlib.Path | None = None,
) -> Generated:
    """The proxy and account config texts of one company, refused with `ConfigError` when either breaks a rule."""
    root = _root(root)
    try:
        names.check(company)
    except names.CompanyNameError as exc:
        raise ConfigError(str(exc)) from None
    if not D1_ID_RE.fullmatch(d1_id):
        raise ConfigError("the D1 database id %r is not a uuid" % (d1_id,))
    regions, entry = _region(region, root)
    extra = _check_allow_ips(allow_ips)
    target = pc.company_target(company, region, regions, PRODUCT_DOMAIN)
    try:
        proxy_template = (root.joinpath(*pc.PROXY_REL) / pc.TEMPLATE).read_text(encoding="utf-8")
        account_template = (root.joinpath(*pc.ACCOUNT_REL) / ACCOUNT_TEMPLATE).read_text(
            encoding="utf-8"
        )
        proxy = pc.render(proxy_template, target, extra)
    except (OSError, pc.ConfigError) as exc:
        raise ConfigError(str(exc)) from None
    jurisdiction = entry.get("r2Jurisdiction")
    values = {
        "HEADER": HEADER,
        "NAME": "account-%s" % company,
        "COMPANY": company,
        "ROUTE_ENTRY": '{ pattern = "%s.%s/*", zone_name = "%s" }'
        % (company, PRODUCT_DOMAIN, PRODUCT_DOMAIN),
        "HOST": "%s.%s" % (company, PRODUCT_DOMAIN),
        "REGION": region,
        "ENVIRONMENT": pc.COMPANY_ENVIRONMENT,
        "EXTRA_VARS": "".join('\n%s = "%s"' % kv for kv in extra),
        "OTLP_LOGS": "otlp-%s-logs" % region,
        "OTLP_TRACES": "otlp-%s-traces" % region,
        "D1_ID": d1_id,
        "R2_JURISDICTION": '\njurisdiction = "%s"' % jurisdiction if jurisdiction else "",
    }
    account = account_template
    for key, value in values.items():
        account = account.replace("@@%s@@" % key, value)
    left = sorted(set(pc.PLACEHOLDER_RE.findall(account)))
    if left:
        raise ConfigError("%s leaves %s unfilled" % (ACCOUNT_TEMPLATE, ", ".join(left)))
    reasons = [
        "proxy: " + r for r in pc.config_refusals(proxy, target, pc._region_tokens(regions))
    ] + ["account: " + r for r in account_refusals(company, region, account, root=root)]
    if reasons:
        raise ConfigError("; ".join(reasons))
    return Generated(proxy=proxy, account=account)


def write(
    company: str,
    region: str,
    d1_id: str,
    *,
    allow_ips: tuple[str, ...] = (),
    root: pathlib.Path | None = None,
    out_root: pathlib.Path | None = None,
) -> list[pathlib.Path]:
    """Generate and write both files under `out_root` (default: the repository), returning the paths."""
    out = generate(company, region, d1_id, allow_ips=allow_ips, root=root)
    base = _root(out_root)
    targets = (
        (base.joinpath(*pc.PROXY_REL) / ("enterprise.%s.toml" % company), out.proxy),
        (base.joinpath(*pc.ACCOUNT_REL) / ("enterprise.%s.toml" % company), out.account),
    )
    for path, text in targets:
        path.write_text(text, encoding="utf-8")
    return [p for p, _ in targets]
