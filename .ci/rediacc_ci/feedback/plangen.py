"""Stage 5 of feedback triage: a draft `agent/plans/PLAN-feedback-<slug>.md` for each confirmed fingerprint with no plan (PLAN-rdc-feedback R9, D5, D6).

The plan is written in the normal plan format with `Status: draft`, a `Feedback:` header line naming the short fingerprint, the public-safe evidence as Context and one `[writer]` box for the fix; the fingerprint then moves to `planned` with `planRef`. Promotion follows the usual agent/plans/QUEUE.md rules; nothing here touches the queue.

PUBLIC-SAFE ONLY (D6, the repository is public). The plan carries the fingerprint, the category, the classifier's summary (already held to `classify.parse_reply`: one line, plain characters, no quote of the report, every Stage 1 rule clean), the command path when it is a plain verb path, the error code when it is a plain code, the exit code, versions and counts. Never argv, stderr, the error message or the reporter's message.

`Owns:` names the plan file alone: the fix's files are not known until the plan is designed, so the generated draft claims no source path and binds no surface.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from typing import TYPE_CHECKING, Any

from rediacc_ci.feedback.classify import (
    COMMAND_PATH,
    REMOTE_CATEGORIES,
    ReplyError,
    parse_reply,
)

if TYPE_CHECKING:
    from collections.abc import Mapping
    from datetime import datetime
    from pathlib import Path

    from rediacc_ci.feedback.classify import Classification

PLANS_DIR = ("agent", "plans")
PREFIX = "PLAN-feedback-"
SLUG_MAX = 48
SHORT_FP = 12
ERROR_CODE = re.compile(r"^[A-Z][A-Z0-9_]{1,63}$")
VERSION = re.compile(r"^v?\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]{1,32})?$")
DEFAULT_OWNER = "feedback-triage"
OWNER = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,31}$")


class PlanError(ValueError):
    """The plan cannot be written: a foreign plan holds the name, or the classification is not plan-safe."""


def slugify(text: str) -> str:
    words = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    out = words[:SLUG_MAX].rstrip("-")
    return out or "report"


def slug_for(cls: Classification) -> str:
    return slugify("%s %s" % (cls.category, cls.summary))


def plan_name(slug: str) -> str:
    return "%s%s.md" % (PREFIX, slug)


def _versions(item: Mapping[str, Any]) -> str:
    versions = [v for v in item.get("versions") or [] if isinstance(v, str) and VERSION.match(v)]
    return ", ".join(versions[:8]) or "unknown"


def _int(item: Mapping[str, Any], key: str) -> int:
    value = item.get(key)
    return value if isinstance(value, int) and not isinstance(value, bool) else 0


def render(
    item: Mapping[str, Any], cls: Classification, owner: str, now: datetime, slug: str
) -> str:
    """The plan text. Every value is public-safe by the module docstring's list."""
    try:
        parse_reply(_reply_json(cls))
    except ReplyError as exc:
        msg = "the classification is not plan-safe (%s)" % exc
        raise PlanError(msg) from None
    if not OWNER.match(owner):
        msg = "owner %r is not a session prefix" % owner
        raise PlanError(msg)
    fp = item["fingerprint"][:SHORT_FP]
    name = plan_name(slug)
    path = item.get("commandPath")
    command = (
        "rdc %s" % path
        if isinstance(path, str) and COMMAND_PATH.match(path)
        else "an unnamed command"
    )
    code = item.get("errorCode")
    code_line = code if isinstance(code, str) and ERROR_CODE.match(code) else "none recorded"
    exit_code = item.get("exitCode")
    exit_line = (
        str(exit_code)
        if isinstance(exit_code, int) and not isinstance(exit_code, bool)
        else "unknown"
    )
    date = now.strftime("%Y-%m-%d")
    where = (
        "on bench (`./rdc.sh --config eu-bench`)"
        if cls.category in REMOTE_CATEGORIES
        else "locally (a named test or `npm run ci -- --narrow`)"
    )
    return "\n".join(
        [
            "# PLAN: feedback %s -- %s" % (fp, cls.summary),
            "",
            "Status: draft -- generated by rediacc_ci.feedback.plangen from a confirmed feedback report; promotion follows the agent/plans/QUEUE.md rules",
            "Depends-On: no-dep -- generated from one confirmed report; the design names its edges",
            "Owner: %s" % owner,
            "First-Seen: %s" % date,
            "Priority: P2 -- a confirmed field report (%s, %d reporter(s), %d occurrence(s))"
            % (cls.category, _int(item, "distinctReporters"), _int(item, "occurrenceCount")),
            "Concurrency: parallel -- one fix box; its files are named when the plan is designed",
            "Owns: agent/plans/%s" % name,
            "Feedback: %s" % fp,
            "",
            "## Context",
            "",
            "- **Report.** Fingerprint `%s`, category `%s`, %s exited %s, error code %s."
            % (fp, cls.category, command, exit_line, code_line),
            "- **Summary.** %s" % cls.summary,
            "- **Spread.** %d report(s), %d occurrence(s), %d reporter(s), %d org(s); versions %s; first seen %s, last seen %s."
            % (
                _int(item, "reportCount"),
                _int(item, "occurrenceCount"),
                _int(item, "distinctReporters"),
                _int(item, "distinctOrgs"),
                _versions(item),
                str(item.get("firstSeenAt", "?"))[:10],
                str(item.get("lastSeenAt", "?"))[:10],
            ),
            "- **Reproduced** %s by the triage agent; the redacted argv and stderr stay in the admin export and never enter this public file."
            % where,
            "",
            "## Boxes",
            "",
            "- [ ] F1 [writer] Fix the %s failure of %s that feedback %s reports"
            % (cls.category, command, fp),
            "    Owns: named when the plan is designed",
            "    Depends on: none.",
            "    Accept: the reproduction above no longer reproduces, and a named regression test fails without the fix and passes with it.",
            "",
        ]
    )


def _reply_json(cls: Classification) -> str:
    return json.dumps(cls.as_dict())


@dataclass(frozen=True)
class Written:
    rel: str
    name: str
    created: bool


def write(
    root: Path,
    item: Mapping[str, Any],
    cls: Classification,
    now: datetime,
    owner: str = DEFAULT_OWNER,
    dry_run: bool = False,
) -> Written:
    """Write the plan under `<root>/agent/plans/`. A file that already names this fingerprint is kept as it is; a file of another fingerprint under the same slug moves this one to `<slug>-<fp8>`."""
    fp = item["fingerprint"][:SHORT_FP]
    base = slug_for(cls)
    plans = root.joinpath(*PLANS_DIR)
    for slug in (base, "%s-%s" % (base, item["fingerprint"][:8])):
        name = plan_name(slug)
        target = plans / name
        rel = "/".join((*PLANS_DIR, name))
        if target.exists():
            if "\nFeedback: %s\n" % fp in target.read_text(encoding="utf-8", errors="replace"):
                return Written(rel, name, created=False)
            continue
        text = render(item, cls, owner, now, slug)
        if not dry_run:
            plans.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
        return Written(rel, name, created=True)
    msg = "both plan names for %s are held by other fingerprints" % fp
    raise PlanError(msg)
