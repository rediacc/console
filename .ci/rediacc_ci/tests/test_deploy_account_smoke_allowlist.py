"""The post-deploy portal smoke on a company whose ALLOW_IPS refuses the deploying machine: no request leaves the process."""

from __future__ import annotations

from typing import TYPE_CHECKING
from urllib.parse import urlparse

from rediacc_ci import paths
from rediacc_ci.deploy import deploy_account as port
from rediacc_ci.enterprise import configs
from rediacc_ci.ops import portal_captcha as pc
from rediacc_ci.well_known import ACCOUNT_DEFAULT_ORIGIN

if TYPE_CHECKING:
    import pathlib

HOST = urlparse(ACCOUNT_DEFAULT_ORIGIN).netloc
SITEKEY = "0x4AAAAAACfixtureKey0001"
ROUTED = 'routes = [\n  { pattern = "%s", custom_domain = true }\n]\n' % HOST
ALLOWLISTED = ROUTED + '[vars]\nALLOW_IPS = "203.0.113.7"\n'
# workers/proxy/src/ip-allowlist.ts `allowlistRefusal`.
ALLOWLIST_BODY = '{"error":"This address is not on the allowlist."}'


def smoke_answering_403(tmp_path: pathlib.Path, toml: str, body: str) -> tuple[str | None, list]:
    config = tmp_path / "wrangler.eu.toml"
    config.write_text(toml)
    calls: list = []

    def fetch(method, url, _body):
        calls.append((method, url))
        return pc.Reply(403, body)

    refusal = port.portal_smoke(config, {"TURNSTILE_SITE_KEY": SITEKEY}, fetch, lambda _s: None)
    return refusal, calls


def test_the_smoke_is_skipped_when_the_company_allowlist_refuses_this_machine(
    tmp_path: pathlib.Path,
) -> None:
    refusal, calls = smoke_answering_403(tmp_path, ALLOWLISTED, ALLOWLIST_BODY)
    assert refusal is None
    assert calls == [("GET", ACCOUNT_DEFAULT_ORIGIN + "/account/login")]


def test_a_403_without_an_allowlist_in_the_config_is_still_a_refusal(
    tmp_path: pathlib.Path,
) -> None:
    refusal, _calls = smoke_answering_403(tmp_path, ROUTED, ALLOWLIST_BODY)
    assert refusal is not None
    assert "UNKNOWN" in refusal


def test_a_403_with_another_body_is_still_a_refusal_under_an_allowlist(
    tmp_path: pathlib.Path,
) -> None:
    for body in ('{"error":"Forbidden"}', "not json", "[]"):
        refusal, _calls = smoke_answering_403(tmp_path, ALLOWLISTED, body)
        assert refusal is not None, body
        assert "UNKNOWN" in refusal


# The account config `set_allowlist` deploys, generated by `enterprise.configs` with only TEST-NET-1 listed (`proof.FOREIGN_IP`).
D1_ID = "11111111-2222-3333-4444-555555555555"
COMPANY_ID = "c0123456789abcdef"


def lab_config(tmp_path: pathlib.Path, allow: tuple[str, ...]) -> pathlib.Path:
    text = configs.generate(
        "acme",
        "eu",
        D1_ID,
        company_id=COMPANY_ID,
        bench=True,
        allow_ips=allow,
        root=paths.repo_root(),
    ).account
    config = tmp_path / ("enterprise.%s.toml" % COMPANY_ID)
    config.write_text(text)
    return config


def smoke_answering(
    config: pathlib.Path, answers: list[pc.Reply]
) -> tuple[str | None, list[tuple[str, str]], list[float]]:
    """`portal_smoke` against a host that answers `answers` in turn, then repeats the last one."""
    calls: list[tuple[str, str]] = []
    sleeps: list[float] = []

    def fetch(method, url, _body):
        calls.append((method, url))
        return answers[min(len(calls), len(answers)) - 1]

    refusal = port.portal_smoke(config, {"TURNSTILE_SITE_KEY": SITEKEY}, fetch, sleeps.append)
    return refusal, calls, sleeps


def test_the_allowlist_refusal_is_recognised_on_a_retried_attempt_after_propagation(
    tmp_path: pathlib.Path,
) -> None:
    """2026-11-16 `proof proxy` rerun: the first answer after the deploy was not yet the new version's, and the one-shot probe then read UNKNOWN 403."""
    config = lab_config(tmp_path, ("192.0.2.10",))
    host = port.route_host(config)
    assert host
    assert port.allow_ips(config) == "192.0.2.10"
    refusal, calls, sleeps = smoke_answering(
        config, [pc.Reply(0, "", "URLError"), pc.Reply(403, ALLOWLIST_BODY)]
    )
    assert refusal is None
    login = ("GET", "https://%s/account/login" % host)
    assert calls == [login, login]
    assert len(sleeps) == 1


def test_the_login_page_is_asked_once_per_attempt_under_an_allowlist(
    tmp_path: pathlib.Path,
) -> None:
    """Review 097d5445.2: no extra probe GET ahead of the retried check."""
    config = lab_config(tmp_path, ("192.0.2.10",))
    refusal, calls, sleeps = smoke_answering(config, [pc.Reply(403, '{"error":"Forbidden"}')])
    assert refusal is not None
    assert "UNKNOWN" in refusal
    assert len(calls) == len(sleeps) + 1 == 6


def test_the_lab_config_without_an_allowlist_still_refuses_the_allowlist_body(
    tmp_path: pathlib.Path,
) -> None:
    config = lab_config(tmp_path, ())
    assert port.allow_ips(config) == ""
    refusal, _calls, _sleeps = smoke_answering(config, [pc.Reply(403, ALLOWLIST_BODY)])
    assert refusal is not None
    assert "UNKNOWN" in refusal


def test_a_vars_that_is_not_a_table_reads_as_no_allowlist(tmp_path: pathlib.Path) -> None:
    """Review 097d5445.1: a `vars` that is not a table answers "" as the docstring says, never an AttributeError."""
    config = tmp_path / "wrangler.eu.toml"
    for text in (ROUTED + 'vars = "x"\n', ROUTED + "vars = [1]\n"):
        config.write_text(text)
        assert port.allow_ips(config) == ""
