"""The post-deploy proxy smoke on a company whose ALLOW_IPS refuses the deploying machine: no request leaves the process.

The 2026-11-16 V7 `proof proxy` bench run failed "the allowlist names only a foreign address" with "/v1/health answered 403, expected 200" (proxy-1.log:623 and :1231): the proxy Worker applies ALLOW_IPS to every route, /v1/health included (workers/proxy/src/ip-allowlist.ts).
"""

from __future__ import annotations

import time
import types
from typing import TYPE_CHECKING

from rediacc_ci import paths
from rediacc_ci.deploy import deploy_proxy as port
from rediacc_ci.enterprise import configs

if TYPE_CHECKING:
    import pathlib

    import pytest

HOST = "c0123456789abcdef-proxy.example"
VERSION = "22222222-2222-4222-8222-222222222222"
# workers/proxy/src/ip-allowlist.ts `allowlistRefusal`.
ALLOWLIST_BODY = '{"error":"This address is not on the allowlist."}'
D1_ID = "11111111-2222-3333-4444-555555555555"
COMPANY_ID = "c0123456789abcdef"


def lab_config(tmp_path: pathlib.Path, allow: tuple[str, ...]) -> pathlib.Path:
    """The proxy config `set_allowlist` deploys, generated by `enterprise.configs` (bench, TEST-NET-1 listed)."""
    text = configs.generate(
        "acme",
        "eu",
        D1_ID,
        company_id=COMPANY_ID,
        bench=True,
        allow_ips=allow,
        root=paths.repo_root(),
    ).proxy
    config = tmp_path / ("enterprise.%s.toml" % COMPANY_ID)
    config.write_text(text)
    return config


class Host:
    """Scripted answers per path: `codes` feed `_curl` (status only) and `bodies` feed `_curl_body` ((body, status)); each list's last entry repeats. Records every URL asked, in order."""

    def __init__(
        self, codes: dict[str, list[str]], bodies: dict[str, list[tuple[str, str]]]
    ) -> None:
        self.codes = codes
        self.bodies = bodies
        self.asked: list[tuple[str, str]] = []

    def _path(self, url: str) -> str:
        return url.removeprefix("https://" + HOST)

    def curl(self, url: str, _pin: str | None = None) -> tuple[str, int]:
        path = self._path(url)
        self.asked.append(("code", path))
        answers = self.codes[path]
        return answers[min(sum(1 for a in self.asked if a == ("code", path)), len(answers)) - 1], 0

    def curl_body(self, url: str, _pin: str | None = None) -> tuple[str, str]:
        path = self._path(url)
        self.asked.append(("body", path))
        answers = self.bodies[path]
        return answers[min(sum(1 for a in self.asked if a == ("body", path)), len(answers)) - 1]


def run_smoke(monkeypatch: pytest.MonkeyPatch, host: Host, config: pathlib.Path | None) -> int:
    monkeypatch.setattr(port, "_curl", host.curl)
    monkeypatch.setattr(port, "_curl_body", host.curl_body)
    monkeypatch.setattr(port, "_sleep", lambda _s: None)
    monkeypatch.setattr(port, "READY_TIMEOUT_S", 0.0)
    return port.smoke(HOST, VERSION, config=config)


def ready(version: str) -> tuple[str, str]:
    return '{"ready": true, "workerVersion": "%s"}' % version, "200"


def test_a_health_403_from_the_allowlist_skips_the_smoke(
    monkeypatch: pytest.MonkeyPatch, tmp_path: pathlib.Path, capsys: pytest.CaptureFixture[str]
) -> None:
    config = lab_config(tmp_path, ("192.0.2.10",))
    assert port.allow_ips(config) == "192.0.2.10"
    host = Host({"/v1/health": ["403"]}, {"/v1/health": [(ALLOWLIST_BODY, "403")]})
    assert run_smoke(monkeypatch, host, config) == 0
    assert host.asked == [("code", "/v1/health"), ("body", "/v1/health")]
    out = capsys.readouterr()
    assert "Smoke skipped" in out.out + out.err
    assert "ALLOW_IPS refuses this machine" in out.out + out.err
    assert "Smoke test failed" not in out.err


def test_a_health_403_without_an_allowlist_still_fails(
    monkeypatch: pytest.MonkeyPatch, tmp_path: pathlib.Path, capsys: pytest.CaptureFixture[str]
) -> None:
    config = lab_config(tmp_path, ())
    assert port.allow_ips(config) == ""
    host = Host({"/v1/health": ["403"]}, {"/v1/health": [(ALLOWLIST_BODY, "403")]})
    assert run_smoke(monkeypatch, host, config) == 1
    assert host.asked == [("code", "/v1/health")]
    assert "/v1/health answered 403, expected 200" in capsys.readouterr().err


def test_a_smoke_given_no_config_reads_no_allowlist(
    monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    host = Host({"/v1/health": ["403"]}, {"/v1/health": [(ALLOWLIST_BODY, "403")]})
    assert run_smoke(monkeypatch, host, None) == 1
    assert "/v1/health answered 403, expected 200" in capsys.readouterr().err


def test_another_403_body_under_an_allowlist_still_fails(
    monkeypatch: pytest.MonkeyPatch, tmp_path: pathlib.Path, capsys: pytest.CaptureFixture[str]
) -> None:
    config = lab_config(tmp_path, ("192.0.2.10",))
    for body in ('{"error":"Forbidden"}', "not json", "[]", ""):
        host = Host({"/v1/health": ["403"]}, {"/v1/health": [(body, "403")]})
        assert run_smoke(monkeypatch, host, config) == 1, body
        assert "/v1/health answered 403, expected 200" in capsys.readouterr().err


def test_the_refusal_is_recognised_on_server_info_after_an_old_version_answered_health(
    monkeypatch: pytest.MonkeyPatch, tmp_path: pathlib.Path
) -> None:
    """Right after the deploy an edge may still serve the previous version for /v1/health; the next request is the allowlisted one."""
    config = lab_config(tmp_path, ("192.0.2.10",))
    host = Host(
        {"/v1/health": ["200"], "/v1/server-info": ["403"]},
        {"/v1/server-info": [(ALLOWLIST_BODY, "403")]},
    )
    assert run_smoke(monkeypatch, host, config) == 0
    assert host.asked[-1] == ("body", "/v1/server-info")


def test_the_refusal_is_recognised_on_a_later_ready_poll(
    monkeypatch: pytest.MonkeyPatch, tmp_path: pathlib.Path
) -> None:
    config = lab_config(tmp_path, ("192.0.2.10",))
    host = Host(
        {"/v1/health": ["200"], "/v1/server-info": ["401"]},
        {"/v1/ready": [ready("old"), (ALLOWLIST_BODY, "403")]},
    )
    monkeypatch.setattr(port, "_curl", host.curl)
    monkeypatch.setattr(port, "_curl_body", host.curl_body)
    # The poll gets exactly two asks: the deadline passes after the second, so a smoke that misses the refusal fails at once.
    sleeps: list[float] = []
    monkeypatch.setattr(port, "_sleep", sleeps.append)
    monkeypatch.setattr(port, "READY_TIMEOUT_S", 1000.0)
    # health and server-info deadlines, the ready deadline, the check after the first poll; then past it.
    clock = iter([0.0, 0.0, 0.0, 0.0])
    monkeypatch.setattr(
        port,
        "time",
        types.SimpleNamespace(
            monotonic=lambda: next(clock, 2000.0), perf_counter=time.perf_counter
        ),
    )
    assert port.smoke(HOST, VERSION, config=config) == 0
    assert host.asked.count(("body", "/v1/ready")) == 2
    assert len(sleeps) == 1


def test_a_ready_403_with_another_body_still_times_out_under_an_allowlist(
    monkeypatch: pytest.MonkeyPatch, tmp_path: pathlib.Path, capsys: pytest.CaptureFixture[str]
) -> None:
    config = lab_config(tmp_path, ("192.0.2.10",))
    host = Host(
        {"/v1/health": ["200"], "/v1/server-info": ["401"]},
        {"/v1/ready": [('{"error":"Forbidden"}', "403")]},
    )
    assert run_smoke(monkeypatch, host, config) == 1
    assert "/v1/ready did not answer 200" in capsys.readouterr().err


def test_an_allowlisted_company_that_admits_this_machine_is_smoked_in_full(
    monkeypatch: pytest.MonkeyPatch, tmp_path: pathlib.Path
) -> None:
    """Control: ALLOW_IPS set and this machine listed, so every request answers and the smoke passes on the version."""
    config = lab_config(tmp_path, ("192.0.2.10",))
    host = Host(
        {"/v1/health": ["200"], "/v1/server-info": ["401"]}, {"/v1/ready": [ready(VERSION)]}
    )
    assert run_smoke(monkeypatch, host, config) == 0
    assert host.asked == [
        ("code", "/v1/health"),
        ("code", "/v1/server-info"),
        ("body", "/v1/ready"),
    ]


def test_the_skip_is_reported_in_the_outcome_a_full_pass_leaves_empty(
    monkeypatch: pytest.MonkeyPatch, tmp_path: pathlib.Path
) -> None:
    """Review 9acc621c.1: rc 0 alone cannot tell the skip from a verified pass, so `outcome` names it; the control pass leaves it unset."""
    config = lab_config(tmp_path, ("192.0.2.10",))
    refused = Host({"/v1/health": ["403"]}, {"/v1/health": [(ALLOWLIST_BODY, "403")]})
    skipped: dict[str, object] = {}
    monkeypatch.setattr(port, "_curl", refused.curl)
    monkeypatch.setattr(port, "_curl_body", refused.curl_body)
    monkeypatch.setattr(port, "_sleep", lambda _s: None)
    assert port.smoke(HOST, VERSION, config=config, outcome=skipped) == 0
    assert skipped == {"smoke_skipped": "allowlist"}
    full = Host(
        {"/v1/health": ["200"], "/v1/server-info": ["401"]}, {"/v1/ready": [ready(VERSION)]}
    )
    monkeypatch.setattr(port, "_curl", full.curl)
    monkeypatch.setattr(port, "_curl_body", full.curl_body)
    passed: dict[str, object] = {}
    assert port.smoke(HOST, VERSION, config=config, outcome=passed) == 0
    assert passed == {}


def test_a_refusal_body_with_an_extra_key_is_not_the_allowlist(
    monkeypatch: pytest.MonkeyPatch, tmp_path: pathlib.Path
) -> None:
    """Review 9acc621c.2: the body must be exactly the one-key refusal; control: the exact body is recognised."""
    extra = '{"error":"This address is not on the allowlist.","x":1}'
    assert port.allowlist_refused(403, ALLOWLIST_BODY)
    assert not port.allowlist_refused(403, extra)
    config = lab_config(tmp_path, ("192.0.2.10",))
    host = Host({"/v1/health": ["403"]}, {"/v1/health": [(extra, "403")]})
    assert run_smoke(monkeypatch, host, config) == 1
