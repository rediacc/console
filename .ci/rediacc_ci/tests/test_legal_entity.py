"""`rediacc_ci.legal.entity`: the projection of the ten SELLER_* vault entries, and the verify that holds it equal to them.

Every case drives fake vault values chosen so that each is a distinctive marker, and asserts that no marker reaches stdout or stderr: the verify prints FIELD NAMES, never values. The vault is the environment the `legal-entity` profile would bind; the unreachable-vault case injects the child runner that `bws_env exec` would be, failing.
"""

from __future__ import annotations

import json
import typing

import pytest

from rediacc_ci import paths
from rediacc_ci.legal import entity

if typing.TYPE_CHECKING:
    import pathlib

VAULT = {
    "SELLER_NAME": "Marker Legal OU",
    "SELLER_REGISTRATION_NUMBER": "MARK-REG-111",
    "SELLER_REGISTER_NAME": "Marker Register",
    "SELLER_VAT_NUMBER": "MARKVAT222",
    "SELLER_ADDRESS_LINE1": "Marker Street 1",
    "SELLER_ADDRESS_LINE2": "Marker District",
    "SELLER_CITY": "Marker County, Marker City",
    "SELLER_POSTAL_CODE": "M3333",
    "SELLER_COUNTRY": "EE",
    "SELLER_EMAIL": "marker@example.invalid",
}
HYDRATED = {**VAULT, entity.PROFILES_ENV: "legal-entity"}


def _no_value_in(text: str) -> None:
    for name, value in VAULT.items():
        if name == "SELLER_COUNTRY":
            continue
        assert value not in text, "the value of %s reached a stream" % name


def _synced(tmp_path: pathlib.Path) -> pathlib.Path:
    assert entity.main(["sync"], env=HYDRATED, root=tmp_path) == 0
    return tmp_path


def test_the_vault_names_are_the_legal_entity_profile() -> None:
    supply = json.loads(paths.from_root(".ci", "config", "secret-supply.json").read_text("utf-8"))
    profile = supply["consumers"][entity.PROFILE]
    assert sorted(profile["required"]) == sorted(entity.VAULT_NAMES)
    assert len(entity.VAULT_NAMES) == 10
    assert profile["optional"] == []


def test_sync_writes_the_projection_with_sorted_keys_and_no_email(
    tmp_path: pathlib.Path, capsys: pytest.CaptureFixture[str]
) -> None:
    root = _synced(tmp_path)
    doc = json.loads(root.joinpath(*entity.JSON_REL).read_text("utf-8"))
    assert list(doc) == sorted(doc)
    assert doc["legalName"] == "Marker Legal OU"
    assert doc["registryCode"] == "MARK-REG-111"
    assert doc["registerName"] == "Marker Register"
    assert doc["countryCode"] == "EE"
    assert doc["registeredAddress"] == (
        "Marker County, Marker City, Marker District, Marker Street 1, M3333"
    )
    assert doc["sourceSha256"] == entity.source_sha256(VAULT)
    assert "marker@example.invalid" not in json.dumps(doc), (
        "SELLER_EMAIL is hashed, never projected"
    )
    assert "licensorName" not in doc
    ts = root.joinpath(*entity.TS_REL).read_text("utf-8")
    assert ts.startswith("// AUTO-GENERATED by `./run.sh legal-entity sync`")
    assert "export const LEGAL_ENTITY = {" in ts
    assert "  legalName: 'Marker Legal OU',\n" in ts
    out = capsys.readouterr()
    _no_value_in(out.out + out.err)


def test_verify_passes_on_a_fresh_sync(
    tmp_path: pathlib.Path, capsys: pytest.CaptureFixture[str]
) -> None:
    root = _synced(tmp_path)
    capsys.readouterr()
    assert entity.main(["verify"], env=HYDRATED, root=root) == 0
    out = capsys.readouterr()
    _no_value_in(out.out + out.err)


@pytest.mark.parametrize("name", sorted(VAULT))
def test_verify_exits_1_on_a_one_field_drift_naming_no_value(
    name: str, tmp_path: pathlib.Path, capsys: pytest.CaptureFixture[str]
) -> None:
    root = _synced(tmp_path)
    capsys.readouterr()
    drifted = {**HYDRATED, name: ("FR" if name == "SELLER_COUNTRY" else VAULT[name] + " DRIFTED")}
    assert entity.main(["verify"], env=drifted, root=root) == 1
    out = capsys.readouterr()
    text = out.out + out.err
    _no_value_in(text)
    assert "DRIFTED" not in text
    # The hash moves on every drift (the email is inside it), and a projected field is named by its key.
    assert "field sourceSha256 differs from the vault" in out.err
    key = dict(entity.FIELDS)[name]
    if key is not None:
        assert "field %s differs from the vault" % key in out.err


def test_verify_exits_1_on_a_hand_edited_ts_file(
    tmp_path: pathlib.Path, capsys: pytest.CaptureFixture[str]
) -> None:
    root = _synced(tmp_path)
    ts = root.joinpath(*entity.TS_REL)
    ts.write_text(ts.read_text("utf-8").replace("Marker Legal OU", "Hand Edit OU"), "utf-8")
    capsys.readouterr()
    assert entity.main(["verify"], env=HYDRATED, root=root) == 1
    out = capsys.readouterr()
    assert "entity.generated.ts differs" in out.err
    assert "Hand Edit OU" not in out.err + out.out


def test_verify_exits_1_on_a_missing_entry_naming_it(
    tmp_path: pathlib.Path, capsys: pytest.CaptureFixture[str]
) -> None:
    root = _synced(tmp_path)
    capsys.readouterr()
    partial = {k: v for k, v in HYDRATED.items() if k != "SELLER_REGISTER_NAME"}
    assert entity.main(["verify"], env=partial, root=root) == 1
    out = capsys.readouterr()
    assert "SELLER_REGISTER_NAME" in out.err
    _no_value_in(out.out + out.err)


def test_verify_exits_1_when_the_vault_cannot_be_reached(
    tmp_path: pathlib.Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """Outside a hydrated profile, verify re-runs itself under `bws_env exec --profile legal-entity`. A refusal there (no token, an unreachable store) is a failure, never a pass."""
    seen: list[list[str]] = []

    def unreachable(argv: list[str], env: dict[str, str]) -> int:
        seen.append(argv)
        assert entity.PROFILES_ENV not in env or "legal-entity" not in env[entity.PROFILES_ENV]
        return 3

    assert entity.main(["verify"], env={}, root=tmp_path, run_child=unreachable) == 1
    assert len(seen) == 1
    assert seen[0][1:6] == ["-m", "rediacc_ci.core.bws_env", "exec", "--profile", "legal-entity"]
    assert seen[0][-3:] == ["-m", "rediacc_ci.legal.entity", "verify"]
    out = capsys.readouterr()
    assert "never a pass" in out.err


def test_a_reachable_vault_passes_the_child_verdict_through(tmp_path: pathlib.Path) -> None:
    assert entity.main(["verify"], env={}, root=tmp_path, run_child=lambda _a, _e: 0) == 0


def test_a_country_that_is_not_an_iso_code_is_refused(
    tmp_path: pathlib.Path, capsys: pytest.CaptureFixture[str]
) -> None:
    assert entity.main(["sync"], env={**HYDRATED, "SELLER_COUNTRY": "Estonia"}, root=tmp_path) == 1
    out = capsys.readouterr()
    assert "SELLER_COUNTRY" in out.err
    assert "Estonia" not in out.err
    assert not tmp_path.joinpath(*entity.JSON_REL).exists()


def test_usage_errors_exit_2(capsys: pytest.CaptureFixture[str]) -> None:
    assert entity.main([], env=HYDRATED) == 2
    assert entity.main(["push"], env=HYDRATED) == 2
    assert "sync|verify" in capsys.readouterr().err


def test_a_single_quote_value_renders_as_valid_typescript() -> None:
    assert entity._ts_string("O'Brien OU") == '"O\'Brien OU"'
    assert entity._ts_string("plain") == "'plain'"
    assert entity._ts_string("both ' and \"") == "'both \\' and \"'"


def test_the_committed_projection_matches_its_own_render() -> None:
    """The committed files agree with each other: the .ts is the render of the .json. The vault comparison is `verify`'s job, run where the vault is reachable."""
    root = paths.repo_root()
    doc = json.loads(root.joinpath(*entity.JSON_REL).read_text("utf-8"))
    assert root.joinpath(*entity.TS_REL).read_text("utf-8") == entity.render_ts(doc)
    assert list(doc) == sorted(doc)
    assert set(doc) == {key for _n, key in entity.FIELDS if key} | {
        "registeredAddress",
        "sourceSha256",
    }
