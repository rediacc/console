/**
 * The shape of packages/cli/src/services/tools/opentofu-pin.generated.ts, the OpenTofu pin
 * `rdc tools install tofu` checks every download against (agent/plans/PLAN-cli-tofu-toolchain.md T1).
 *
 * WHO WRITES IT. `npm run pins -- bump cli-tool:opentofu`: the toolchain driver rewrites the
 * version and the six sha256 values at the sites .ci/config/pins.json names, after
 * scripts/pins/signed-release.ts verified the release's signed SHA256SUMS. This module is the
 * file's template: it wrote the first copy (`--write <version>` over the recorded SHA256SUMS), and
 * `npm run pins -- --selftest` holds the live file byte-equal to `render()` of its own values, so a
 * hand edit of any line the sites do not cover (a URL, a key, the header) is red too.
 *
 * Usage:
 *   npx tsx scripts/pins/opentofu-pin.ts --check            the live file equals render(its values)
 *   npx tsx scripts/pins/opentofu-pin.ts --write            render from the recorded SHA256SUMS
 *                                                           (scripts/pins/data/opentofu), which must
 *                                                           verify offline first
 */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { WK_GH_ORIGIN } from '../../packages/shared/src/config/well-known.generated.js';
import { isEntryPoint } from '../lib/entry-point.js';
import { REPO_ROOT } from '../lib/repo-root.js';
import {
  offlineProblems,
  parseSums,
  readEvidence,
  SIGNED_RELEASES,
  versionOfSums,
} from './signed-release.js';

export const PIN_ID = 'cli-tool:opentofu';
export const GENERATED_REL = 'packages/cli/src/services/tools/opentofu-pin.generated.ts';

/** The six platforms rdc installs OpenTofu on, as `<os>-<arch>` (the sha256 role suffix). */
export const PLATFORMS = [
  'linux-amd64',
  'linux-arm64',
  'darwin-amd64',
  'darwin-arm64',
  'windows-amd64',
  'windows-arm64',
] as const;
export type Platform = (typeof PLATFORMS)[number];

/** The release asset of a platform: the zip archive, the one format OpenTofu publishes for all six. */
export const assetOf = (version: string, p: Platform): string =>
  `tofu_${version}_${p.replace('-', '_')}.zip`;

export const urlOf = (version: string, p: Platform): string =>
  `${WK_GH_ORIGIN}/opentofu/opentofu/releases/download/v${version}/${assetOf(version, p)}`;

/** The file, whole, for `version` and its six digests. */
export function render(version: string, digests: Record<Platform, string>): string {
  const rows = PLATFORMS.map(
    (p) => `    '${p}': { url: '${urlOf(version, p)}', sha256: '${digests[p]}' },`
  );
  return [
    `// AUTO-GENERATED by npm run pins -- bump ${PIN_ID} - DO NOT EDIT`,
    '// Source: .ci/config/pins.json entry cli-tool:opentofu. Each sha256 comes from the release SHA256SUMS after its',
    '// cosign keyless signature verified (scripts/pins/signed-release.ts), and check:ci-pin-registry holds every value',
    '// equal to the recorded scripts/pins/data/opentofu/SHA256SUMS. Template: scripts/pins/opentofu-pin.ts.',
    '',
    'export const OPENTOFU_PIN = {',
    `  version: '${version}',`,
    '  assets: {',
    ...rows,
    '  },',
    '} as const;',
    '',
  ].join('\n');
}

/** The version and digests a rendered file carries; null when it is not in the rendered shape. */
export function parse(text: string): { version: string; digests: Record<Platform, string> } | null {
  const version = /^ {2}version: '([^']+)',$/m.exec(text)?.[1];
  if (!version) return null;
  const digests = {} as Record<Platform, string>;
  for (const p of PLATFORMS) {
    const d = new RegExp(`^ {4}'${p}': \\{ url: '[^']+', sha256: '([0-9a-f]{64})' \\},$`, 'm').exec(
      text
    )?.[1];
    if (!d) return null;
    digests[p] = d;
  }
  return { version, digests };
}

/** Why the file at `root` is not render() of its own values; null when it is. */
export function driftOf(root: string = REPO_ROOT): string | null {
  const abs = path.join(root, GENERATED_REL);
  if (!fs.existsSync(abs)) return `${GENERATED_REL} does not exist`;
  const text = fs.readFileSync(abs, 'utf8');
  const got = parse(text);
  if (!got)
    return `${GENERATED_REL} is not in the rendered shape (a version line and six platform rows)`;
  const want = render(got.version, got.digests);
  if (want === text) return null;
  const a = text.split('\n');
  const b = want.split('\n');
  const i = a.findIndex((l, n) => l !== b[n]);
  return `${GENERATED_REL} line ${i + 1} differs from the template: ${JSON.stringify(a[i])} vs ${JSON.stringify(b[i])}`;
}

function main(argv: string[]): number {
  if (argv[0] === '--check') {
    const drift = driftOf();
    if (drift) {
      console.error(`opentofu-pin: ${drift}; regenerate with npm run pins -- bump ${PIN_ID}`);
      return 1;
    }
    console.log(
      `opentofu-pin: ${GENERATED_REL} matches its template (${PLATFORMS.length} platforms)`
    );
    return 0;
  }
  if (argv[0] === '--write') {
    const spec = SIGNED_RELEASES[PIN_ID];
    const files = readEvidence(REPO_ROOT, spec);
    const version = files && versionOfSums(files.sums);
    if (!files || !version) {
      console.error(`opentofu-pin: no readable record under ${spec.evidence}`);
      return 1;
    }
    const problems = offlineProblems(files, spec, version);
    if (problems.length > 0) {
      console.error(`opentofu-pin: the record does not verify:\n  - ${problems.join('\n  - ')}`);
      return 1;
    }
    const listed = parseSums(files.sums);
    const digests = {} as Record<Platform, string>;
    for (const p of PLATFORMS) {
      const d = listed.get(assetOf(version, p));
      if (!d) {
        console.error(`opentofu-pin: SHA256SUMS lists no ${assetOf(version, p)}`);
        return 1;
      }
      digests[p] = d;
    }
    fs.mkdirSync(path.dirname(path.join(REPO_ROOT, GENERATED_REL)), { recursive: true });
    fs.writeFileSync(path.join(REPO_ROOT, GENERATED_REL), render(version, digests));
    console.log(
      `opentofu-pin: wrote ${GENERATED_REL} for OpenTofu ${version} (${PLATFORMS.length} platforms)`
    );
    return 0;
  }
  console.error('usage: opentofu-pin.ts --check | --write');
  return 2;
}

if (isEntryPoint(import.meta.filename)) process.exit(main(process.argv.slice(2)));
