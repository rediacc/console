/**
 * Command safety table (CS2, D2 of PLAN-console-contract-semantics).
 *
 * Every contract command declares a severity, and the commands that can run
 * as a preview declare the flag and its polarity. The table is separate from
 * command-metadata.ts: severity covers all commands, MCP metadata only some.
 *
 * Drafting rule: `destructive` deletes or overwrites state that is not
 * trivially undone; `caution` changes state reversibly; `none` reads.
 * The full list is put to the operator once (CS12).
 */

export type CommandSeverity = 'none' | 'caution' | 'destructive';

export type PreviewPolarity = 'opt-in' | 'default';

export interface CommandPreview {
  /** Long option name without dashes, e.g. `dry-run`. */
  flag: string;
  /** `opt-in`: the flag makes the run a preview. `default`: the command previews unless the flag is given. */
  polarity: PreviewPolarity;
}

