/**
 * `--bws-project <id>`: copy the box's generated secrets to a Bitwarden Secrets Manager project,
 * for installs Rediacc runs itself. Without the flag nothing leaves the box.
 *
 * Names are opaque, `ONPREM_<sha256(domain)[:12]>_<KEY>`, so the domain never appears in the store.
 * An entry holding the same value is left; a different value is refused unless `--rotate`, which
 * edits it. No value is ever printed.
 */

import { createHash } from 'node:crypto';
import { t } from '../../i18n/index.js';
import { outputService } from '../core/output.js';
import { type RepoOnBox, ServerError } from './box.js';
import { parseEnvLines, readKeysScript, shCommand } from './box-scripts.js';
import type { BwsRow, ServerDeps } from './types.js';

export const BWS_BACKUP_KEYS = [
  'ACCOUNT_ED25519_PRIVATE_KEY',
  'ACCOUNT_ED25519_PUBLIC_KEY',
  'ACCOUNT_X25519_PRIVATE_KEY',
  'ACCOUNT_X25519_PUBLIC_KEY',
  'ACCOUNT_CONFIG_SERVER_KEY',
  'RUSTFS_ACCESS_KEY',
  'RUSTFS_SECRET_KEY',
  'ACCOUNT_SERVER_API_KEY',
  'ACCOUNT_JWT_SECRET',
] as const;

export const BWS_NAME = /^ONPREM_[0-9a-f]{12}_[A-Z][A-Z0-9_]*$/;
export const BWS_NOTE = 'on-prem Elite install secret; generated by rdc server install';

export function bwsName(domain: string, key: string): string {
  return `ONPREM_${createHash('sha256').update(domain).digest('hex').slice(0, 12)}_${key}`;
}

export interface BwsBackupResult {
  created: number;
  unchanged: number;
  rotated: number;
}

/** One key: created when absent, left when equal, edited under --rotate, refused otherwise. */
async function syncEntry(
  deps: ServerDeps,
  rows: BwsRow[],
  opts: { domain: string; projectId: string; rotate: boolean },
  key: string,
  value: string
): Promise<keyof BwsBackupResult> {
  const name = bwsName(opts.domain, key);
  if (!BWS_NAME.test(name)) throw new ServerError(t('commands.server.bws.badName'));
  const held = rows.find((r) => r.key === name);
  const base = { key: name, value, note: BWS_NOTE, projectIds: [opts.projectId] as [string] };
  if (!held) {
    await deps.bwsWrite({ op: 'create', ...base });
    return 'created';
  }
  if (held.value === value) return 'unchanged';
  if (!opts.rotate) throw new ServerError(t('commands.server.bws.differs', { key }));
  await deps.bwsWrite({ op: 'edit', id: held.id, ...base });
  return 'rotated';
}

export async function backupToBws(
  deps: ServerDeps,
  where: RepoOnBox,
  opts: { domain: string; projectId: string; rotate: boolean }
): Promise<BwsBackupResult> {
  const read = await deps.ssh(
    where.machine,
    shCommand(readKeysScript(BWS_BACKUP_KEYS), [where.dir])
  );
  if (read.code !== 0) throw new ServerError(t('commands.server.bws.readFailed'));
  const values = parseEnvLines(read.stdout);
  const missing = BWS_BACKUP_KEYS.filter((k) => !values[k]);
  if (missing.length > 0) {
    throw new ServerError(
      t('commands.server.errors.bundleIncomplete', { keys: missing.join(', ') })
    );
  }

  const rows = (await deps.bwsList()).filter((r) => r.projectId === opts.projectId);
  const result: BwsBackupResult = { created: 0, unchanged: 0, rotated: 0 };
  for (const key of BWS_BACKUP_KEYS) {
    const outcome = await syncEntry(deps, rows, opts, key, values[key] ?? '');
    result[outcome]++;
  }
  outputService.info(t('commands.server.bws.done', { ...result }));
  return result;
}
